    assert source =~ "static #{bool} *#{true_k}(void) { return &#{true_obj}; }"
    assert source =~ "static #{bool} #{false_obj} = {1};"
    assert source =~ "static #{bool} *#{false_k}(void) { return &#{false_obj}; }"
