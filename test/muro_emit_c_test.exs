    assert header =~ "/* generated by muro — do not edit */"

    assert header =~
             "struct muro__nat { uint8_t muro__field_tag; muro__nat *muro__field_suc; }; /* 0 = zero, 1 = suc */"

    assert header =~ "muro__nat *half(muro__nat *n);"
    assert header =~ "muro__nat *plus(muro__nat *n, muro__nat *m);"
    assert header =~ "#ifndef muro__ALLOC"
    assert header =~ "#define muro__ALLOC(n) malloc(n)"
    refute header =~ "IsEven"
    refute header =~ "half_ok("

    assert source =~ "muro__zero"
    assert source =~ "muro__suc"
    refute source =~ "static muro__nat *half"
    assert source =~ "half("
    assert source =~ "muro__ALLOC(sizeof *muro__p)"
    refute source =~ "malloc("

    cc!(dir, "half_ok.c", "half_ok.o")
  end

  test "an exported Nat run loads as a NIF" do
    dir = tmp_dir()
    path = Path.join(dir, "half_ok.muro")
    File.cp!("examples/half_ok.muro", path)

    out = capture_io(fn -> Mix.Tasks.Muro.Emit.run([path, "--backend", "c"]) end)
    assert out =~ Path.join(dir, "priv/half_ok.so")
    assert File.exists?(Path.join(dir, "priv/half_ok.so"))

    on_exit(fn ->
      :code.purge(HalfOk)
      :code.delete(HalfOk)
    end)

    Code.compile_file(Path.join(dir, "half_ok.ex"))
    half = fn n -> apply(:"Elixir.HalfOk", :half, [n]) end
    plus = fn n, m -> apply(:"Elixir.HalfOk", :plus, [n, m]) end
    assert half.(0) == 0
    assert half.(1) == 0
    assert half.(4) == 2
    assert plus.(2, 3) == 5
    assert_raise ArgumentError, fn -> half.(-1) end
    assert_raise ArgumentError, fn -> plus.(:no, 1) end
  end

  test "a NIF exports the source name and calls the C symbol" do
    dir = tmp_dir()

    File.write!(Path.join(dir, "names.muro"), """
    def foo-bar : run Nat := 0
    def foo_bar : run Nat := suc 0
    def answer : run Nat := foo_bar
    def and : run Nat := suc (suc 0)
    def read : run Nat := suc (suc (suc 0))
    """)

    capture_io(fn ->
      Mix.Tasks.Muro.Emit.run([Path.join(dir, "names.muro"), "--backend", "c"])
    end)

    ex = File.read!(Path.join(dir, "names.ex"))
    nif = File.read!(Path.join(dir, "names_nif.c"))
    source = File.read!(Path.join(dir, "names.c"))
    dash = Muro.Emit.C.source_id("foo-bar")
    under = Muro.Emit.C.source_id("foo_bar")
    read = Muro.Emit.C.source_id("read")

    bar = Muro.Emit.elixir_base("foo-bar")
    conj = Muro.Emit.elixir_base("and")
    assert ex =~ "def #{bar}, do:"
    assert ex =~ "def foo_bar, do:"
    assert ex =~ "def answer, do:"
    assert ex =~ "def #{conj}, do:"
    assert ex =~ "def read, do:"
    refute ex =~ "def foo_bar_2"
    refute ex =~ "def #{dash}"
    refute ex =~ "foozubar"
    refute ex =~ "def and,"

    assert source =~ "#{dash}("
    assert source =~ "#{under}("
    assert source =~ "#{read}("
    assert nif =~ ~s|"#{bar}", 0,|
    assert nif =~ ~s|"foo_bar", 0,|
    assert nif =~ ~s|"#{conj}", 0,|
    assert nif =~ ~s|"read", 0,|
    assert nif =~ "#{dash}("
    assert nif =~ "#{under}("
    assert nif =~ "#{read}("
    refute nif =~ ~s|"foo_bar_2"|
    refute nif =~ ~s|"foozubar"|
    refute nif =~ ~s|"#{dash}"|
    refute nif =~ ~s|"#{read}"|

    on_exit(fn ->
      :code.purge(Names)
      :code.delete(Names)
    end)

    Code.compile_file(Path.join(dir, "names.ex"))
    call = fn name -> apply(:"Elixir.Names", name, []) end
    assert call.(String.to_atom(bar)) == 0
    assert call.(:foo_bar) == 1
    assert call.(:answer) == 1
    assert call.(String.to_atom(conj)) == 2
    assert call.(:read) == 3
    assert_raise UndefinedFunctionError, fn -> call.(:foozubar) end
    assert_raise UndefinedFunctionError, fn -> call.(:foo_bar_2) end
  end

