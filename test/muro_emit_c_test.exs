  defp forms_book(samples) do
    runs =
      samples
      |> Enum.with_index()
      |> Enum.map_join("\n", fn {name, i} ->
        "def #{name} : run Nat := #{peano(i)}"
      end)

    """
    ν Stream (A : Type) : Type where
      uncons : Stream A → A × Stream A

    def flow : run Stream Nat :=
      unfold 0 (λ (_ : Nat) → (0, 0))

    def hd : run Π (s : Stream Nat) → Nat :=
      λ (s : Stream Nat) → head s

    #{runs}
    """
  end

  defp peano(0), do: "0"
  defp peano(n), do: "suc (" <> peano(n - 1) <> ")"

  defp step_fns(source) do
    ~r/(muro__step_\d+)\(/
    |> Regex.scan(source)
    |> Enum.map(fn [_, name] -> name end)
    |> Enum.uniq()
  end

  defp link_run!(dir, stem, main) do
    File.write!(Path.join(dir, "main.c"), main)
    cc!(dir, "#{stem}.c", "#{stem}.o")
    cc!(dir, "main.c", "main.o")

    {link, status} =
      System.cmd("cc", ["#{stem}.o", "main.o", "-o", "main_bin"],
        cd: dir,
        stderr_to_stdout: true
      )

    assert status == 0, link
    {out, status} = System.cmd(Path.join(dir, "main_bin"), [], stderr_to_stdout: true)
    assert status == 0, out
    out
  end

  defp tmp_dir do
    dir = Path.join(System.tmp_dir!(), "muro_c_#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)
    dir
  end

  defp cc!(dir, src, obj, extra \\ []) do
    {out, status} =
      System.cmd("cc", extra ++ ["-c", src, "-o", obj], cd: dir, stderr_to_stdout: true)

    assert status == 0, out
  end
