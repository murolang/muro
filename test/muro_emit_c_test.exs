  test "atom spellings that sanitize together get distinct enumerators" do
    dir = tmp_dir()
    path = Path.join(dir, "atoms.muro")

    File.write!(path, """
    def pick : run Π (a : Atom) → Nat :=
      λ (a : Atom) →
        match a motive (λ _ → Nat)
          | :A => 0
          | :a => suc 0
          | :a-b => 0
          | :a_b => suc 0
          | :a' => 0
          | :a_ => suc 0
          | :asc => 0
    """)

    capture_io(fn -> Mix.Tasks.Muro.Emit.run([path, "--backend", "c"]) end)
    header = File.read!(Path.join(dir, "atoms.h"))
    source = File.read!(Path.join(dir, "atoms.c"))
    ids = Enum.map(~w(A a a-b a_b a' a_ asc), &Muro.Emit.C.source_id/1)
    assert length(Enum.uniq(ids)) == 7

    Enum.each(ids, fn id ->
      refute String.contains?(id, "__")
      assert header =~ id
      assert source =~ "case #{id}:"
    end)

    # The enumerators are the source spellings. The parameter `a` shares
    # that namespace, so it takes the next suffix.
    refute Enum.any?(ids, &String.ends_with?(&1, "_2"))
    assert header =~ "muro__nat *pick(muro__atom a_2);"
    cc!(dir, "atoms.c", "atoms.o")
  end

