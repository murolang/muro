defmodule Muro.GenNativeTest do
  use ExUnit.Case, async: false

  @kinds [:c, :rust, :zig, :asm]

  test "c, rust, zig, and asm targets round-trip through gen and gen --check" do
    Enum.each(@kinds, &round_trip/1)
  end

  test "gen --check covers the header beside a c target" do
    dir = project(:c)
    generate!(dir)
    header = Path.join(dir, "lib/half.h")
    assert File.regular?(header)
    assert String.starts_with?(File.read!(header), "// Generated by Muro ")

    File.rm!(header)

    assert check_error(dir) =~ "lib/half.h: missing target for priv/muro/half.muro"

    generate!(dir)
    stamp_version(header, "0.0.1")

    assert check_error(dir) =~
             "lib/half.h: header says Muro 0.0.1, running #{Mix.Tasks.Muro.version()}, from priv/muro/half.muro"
  end

  test "a c target includes the header written beside the target" do
    dir = tmp()
    version = Mix.Tasks.Muro.version()
    File.mkdir_p!(Path.join(dir, "muro"))
    File.cp!("examples/half_ok.muro", Path.join(dir, "muro/half.muro"))

    File.write!(Path.join(dir, "muro.toml"), """
    muro = "#{version}"
    backend = "c"

    [[modules]]
    book = "muro/half.muro"
    target = "src/rounding.c"
    """)

    out = cli!(dir, ["gen"])
    assert out =~ "written src/rounding.c\n"
    assert out =~ "written src/rounding.h\n"

    source = File.read!(Path.join(dir, "src/rounding.c"))
    header = File.read!(Path.join(dir, "src/rounding.h"))
    assert source =~ ~s|#include "rounding.h"|
    refute source =~ ~s|#include "half.h"|
    assert header =~ "muro__nat *half(muro__nat *n);"

    if System.find_executable("cc") do
      {result, status} =
        System.cmd("cc", ["-c", "src/rounding.c", "-o", "rounding.o"],
          cd: dir,
          stderr_to_stdout: true
        )

      assert status == 0, result
      assert File.regular?(Path.join(dir, "rounding.o"))
    end
  end

  test "a derived c header that is a directory is refused before anything is written" do
    dir = tmp()
    version = Mix.Tasks.Muro.version()
    File.mkdir_p!(Path.join(dir, "muro"))
    File.cp!("examples/half_ok.muro", Path.join(dir, "muro/half.muro"))
    File.mkdir_p!(Path.join(dir, "src/rounding.h"))
    File.write!(Path.join(dir, "src/rounding.h/keep"), "leave me\n")

    File.write!(Path.join(dir, "muro.toml"), """
    muro = "#{version}"
    backend = "c"

    [[modules]]
    book = "muro/half.muro"
    target = "src/rounding.c"
    """)

    error =
      in_dir(dir, fn ->
        assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Gen.run([]) end
      end)

    assert error.message =~ "modules entry 1: target is a directory: src/rounding.h"
    refute File.regular?(Path.join(dir, "src/rounding.c"))
    assert File.dir?(Path.join(dir, "src/rounding.h"))
    assert File.read!(Path.join(dir, "src/rounding.h/keep")) == "leave me\n"
  end

  test "gen --check covers the module and the declaration file of a js target" do
    dir = project(:js)
    mjs = "lib/half.mjs"
    dts = "lib/half.d.ts"
    book = Path.join(dir, "priv/muro/half.muro")
    original = File.read!(book)

    out = generate!(dir)
    assert out =~ "written #{mjs}\n"
    assert out =~ "written #{dts}\n"
    assert check!(dir) == "ok\n"

    for rel <- [mjs, dts] do
      path = Path.join(dir, rel)
      file = File.read!(path)
      assert String.starts_with?(file, "// Generated by Muro ")
      assert {:ok, header} = Muro.Gen.parse_header(file)
      assert header.prefix == "// "
      assert header.body_hash == Muro.Gen.body_hash(header.body)

      File.write!(path, file <> "/* touched */\n")
      assert check_error(dir) =~ "hand-edited target"
      assert check_error(dir) =~ rel

      generate!(dir)
      stamp_version(path, "0.0.1")

      assert check_error(dir) =~
               "#{rel}: header says Muro 0.0.1, running #{Mix.Tasks.Muro.version()}, from priv/muro/half.muro"

      generate!(dir)
      differ(path)
      assert check_error(dir) =~ "#{rel}: differs from what priv/muro/half.muro emits"

      generate!(dir)
      File.write!(book, original <> "-- stale\n")
      assert check_error(dir) =~ "#{rel}: stale target"
      assert check_error(dir) =~ "priv/muro/half.muro changed"
      File.write!(book, original)

      File.rm!(path)
      assert check_error(dir) =~ "#{rel}: missing target for priv/muro/half.muro"
      generate!(dir)
    end
  end

  test "a muro.toml javascript target writes the module and the declaration file" do
    dir = tmp()
    version = Mix.Tasks.Muro.version()
    File.mkdir_p!(Path.join(dir, "muro"))
    File.cp!("examples/half_ok.muro", Path.join(dir, "muro/half.muro"))

    File.write!(Path.join(dir, "muro.toml"), """
    muro = "#{version}"
    backend = "js"

    [[modules]]
    book = "muro/half.muro"
    target = "src/half.mjs"
    """)

    out = generate!(dir)
    assert out =~ "written src/half.mjs\n"
    assert out =~ "written src/half.d.ts\n"

    source = File.read!(Path.join(dir, "src/half.mjs"))
    types = File.read!(Path.join(dir, "src/half.d.ts"))
    assert String.starts_with?(source, "// Generated by Muro #{version} ")
    assert String.starts_with?(types, "// Generated by Muro #{version} ")
    assert {:ok, header} = Muro.Gen.parse_header(source)
    assert header.prefix == "// "
    assert header.body_hash == Muro.Gen.body_hash(header.body)
    assert {:ok, types_header} = Muro.Gen.parse_header(types)
    assert types_header.body_hash == Muro.Gen.body_hash(types_header.body)
    assert source =~ "export function half("

    assert check!(dir) == "ok\n"
    assert generate!(dir) =~ "unchanged src/half.mjs\n"
    assert generate!(dir) =~ "unchanged src/half.d.ts\n"
  end

  test "a derived javascript declaration file that is a directory is refused" do
    dir = tmp()
    version = Mix.Tasks.Muro.version()
    File.mkdir_p!(Path.join(dir, "muro"))
    File.cp!("examples/half_ok.muro", Path.join(dir, "muro/half.muro"))
    File.mkdir_p!(Path.join(dir, "src/half.d.ts"))
    File.write!(Path.join(dir, "src/half.d.ts/keep"), "leave me\n")

    File.write!(Path.join(dir, "muro.toml"), """
    muro = "#{version}"
    backend = "js"

    [[modules]]
    book = "muro/half.muro"
    target = "src/half.mjs"
    """)

    error =
      in_dir(dir, fn ->
        assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Gen.run([]) end
      end)

    assert error.message =~ "modules entry 1: target is a directory: src/half.d.ts"
    refute File.regular?(Path.join(dir, "src/half.mjs"))
    assert File.dir?(Path.join(dir, "src/half.d.ts"))
    assert File.read!(Path.join(dir, "src/half.d.ts/keep")) == "leave me\n"
  end

  test "a muro.toml javascript book emits runs beside a spec-only session" do
    dir = tmp()
    version = Mix.Tasks.Muro.version()
    File.mkdir_p!(Path.join(dir, "books"))

    File.write!(Path.join(dir, "books/wire.muro"), """
    data Bool : Type where
      true  : Bool
      false : Bool

    def flip : run Π (b : Bool) → Bool :=
      λ (b : Bool) →
        match b motive (λ _ → Bool)
          | true => false
          | false => true

    data Reply : Type where
      written : Reply
      invalid : Reply

    session ask := recv Bool (send Reply end)

    conform answer : ask :=
      get (b : Bool) (put written done)
    """)

    File.write!(Path.join(dir, "books/user.muro"), """
    import "wire.muro"

    def twice : run Π (b : Bool) → Bool :=
      λ (b : Bool) → flip (flip b)
    """)

    File.write!(Path.join(dir, "muro.toml"), """
    muro = "#{version}"
    backend = "js"

    [[modules]]
    book = "books/user.muro"
    target = "out/user.mjs"
    """)

    out = generate!(dir)
    assert out =~ "written out/user.mjs\n"
    assert out =~ "written out/user.d.ts\n"
    source = File.read!(Path.join(dir, "out/user.mjs"))
    assert source =~ "export function flip("
    assert source =~ "export function twice("
    assert source =~ "export const ask ="
  end

  test "a book the javascript backend refuses names that backend and writes nothing" do
    dir = tmp()
    version = Mix.Tasks.Muro.version()
    File.mkdir_p!(Path.join(dir, "books"))
    File.cp!("examples/place.muro", Path.join(dir, "books/home.muro"))

    File.write!(Path.join(dir, "muro.toml"), """
    muro = "#{version}"
    backend = "js"

    [[modules]]
    book = "books/home.muro"
    target = "out/home.mjs"
    """)

    error =
      in_dir(dir, fn ->
        assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Gen.run([]) end
      end)

    assert error.message =~ "out/home.mjs: books/home.muro is refused by the js backend"
    assert error.message =~ "c:host in home (place)"
    assert error.message =~ "muro.gen wrote nothing"
    refute error.message =~ "does not check"
    refute File.regular?(Path.join(dir, "out/home.mjs"))
    refute File.regular?(Path.join(dir, "out/home.d.ts"))
  end

  test "a run that names a session does not check, and gen writes nothing" do
    dir = tmp()
    version = Mix.Tasks.Muro.version()
    File.mkdir_p!(Path.join(dir, "books"))

    File.write!(Path.join(dir, "books/use.muro"), """
    session ask := recv Nat end
    def use : run Nat := ask
    """)

    File.write!(Path.join(dir, "muro.toml"), """
    muro = "#{version}"
    backend = "js"

    [[modules]]
    book = "books/use.muro"
    target = "out/use.mjs"
    """)

    error =
      in_dir(dir, fn ->
        assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Gen.run([]) end
      end)

    assert error.message =~ "out/use.mjs: books/use.muro does not check"
    assert error.message =~ "ask is a session, not a definition"
    assert error.message =~ "muro.gen wrote nothing"
    refute error.message =~ "is refused by the js backend"
    refute File.regular?(Path.join(dir, "out/use.mjs"))
    refute File.regular?(Path.join(dir, "out/use.d.ts"))
  end

  test "a muro.toml rust target is written by muro gen" do
    dir = tmp()
    version = Mix.Tasks.Muro.version()
    File.mkdir_p!(Path.join(dir, "muro"))
    File.cp!("examples/half_ok.muro", Path.join(dir, "muro/half.muro"))

    File.write!(Path.join(dir, "muro.toml"), """
    muro = "#{version}"
    backend = "rust"

    [[modules]]
    book = "muro/half.muro"
    target = "src/half.rs"
    """)

    out = cli!(dir, ["gen"])
    assert out =~ "written src/half.rs\n"
    source = File.read!(Path.join(dir, "src/half.rs"))
    assert String.starts_with?(source, "// Generated by Muro #{version} ")
    assert {:ok, header} = Muro.Gen.parse_header(source)
    assert header.prefix == "// "
    assert header.body_hash == Muro.Gen.body_hash(header.body)

    assert cli!(dir, ["gen", "--check"]) == "ok\n"
    assert cli!(dir, ["gen"]) =~ "unchanged src/half.rs\n"
  end

  defp round_trip(kind) do
    dir = project(kind)
    rel = target(kind)
    prefix = if kind == :asm, do: "@ ", else: "// "

    out = generate!(dir)
    assert out =~ "written #{rel}\n"
    if kind == :c, do: assert(out =~ "written lib/half.h\n")

    file = File.read!(Path.join(dir, rel))
    assert String.starts_with?(file, prefix <> "Generated by Muro ")
    assert {:ok, header} = Muro.Gen.parse_header(file)
    assert header.prefix == prefix
    assert header.body_hash == Muro.Gen.body_hash(header.body)

    again = generate!(dir)
    assert again =~ "unchanged #{rel}\n"
    assert check!(dir) == "ok\n"

    File.write!(Path.join(dir, rel), file <> "/* touched */\n")
    assert check_error(dir) =~ "hand-edited target"
    assert check_error(dir) =~ rel

    generate!(dir)
    stamp_version(Path.join(dir, rel), "0.0.1")

    assert check_error(dir) =~
             "#{rel}: header says Muro 0.0.1, running #{Mix.Tasks.Muro.version()}"

    generate!(dir)
    differ(Path.join(dir, rel))
    assert check_error(dir) =~ "#{rel}: differs from what priv/muro/half.muro emits"

    generate!(dir)
    book = Path.join(dir, "priv/muro/half.muro")
    File.write!(book, File.read!(book) <> "-- stale\n")
    assert check_error(dir) =~ "#{rel}: stale target"
    assert check_error(dir) =~ "priv/muro/half.muro changed"

    File.rm!(Path.join(dir, rel))
    assert check_error(dir) =~ "#{rel}: missing target for priv/muro/half.muro"
  end

  defp differ(path) do
    {:ok, header} = Muro.Gen.parse_header(File.read!(path))
    body = header.body <> "/* touched */\n"
    hash = Muro.Gen.body_hash(body)

    file =
      Muro.Gen.header(
        header.version,
        header.book,
        header.book_hash,
        hash,
        [],
        header.prefix
      ) <> body

    File.write!(path, file)
  end

  defp stamp_version(path, version) do
    {:ok, header} = Muro.Gen.parse_header(File.read!(path))

    file =
      Muro.Gen.header(
        version,
        header.book,
        header.book_hash,
        header.body_hash,
        [],
        header.prefix
      ) <> header.body

    File.write!(path, file)
  end

  defp project(kind) do
    dir = tmp()
    File.mkdir_p!(Path.join(dir, "priv/muro"))
    File.cp!("examples/half_ok.muro", Path.join(dir, "priv/muro/half.muro"))
    version = Mix.Tasks.Muro.version()

    entry =
      case kind do
        :c -> ~s|{"priv/muro/half.muro", "lib/half.c", [kind: :c]}|
        :rust -> ~s|{"priv/muro/half.muro", "lib/half.rs", [kind: :rust]}|
        :zig -> ~s|{"priv/muro/half.muro", "lib/half.zig", [kind: :zig]}|
        :asm -> ~s|{"priv/muro/half.muro", "lib/half.s", [kind: :asm]}|
        :js -> ~s|{"priv/muro/half.muro", "lib/half.mjs", [kind: :js]}|
      end

    File.write!(Path.join(dir, "muro.exs"), """
    [
      muro: "#{version}",
      modules: [
        #{entry}
      ]
    ]
    """)

    dir
  end

  defp target(:c), do: "lib/half.c"
  defp target(:rust), do: "lib/half.rs"
  defp target(:zig), do: "lib/half.zig"
  defp target(:asm), do: "lib/half.s"

  defp generate!(dir) do
    in_dir(dir, fn ->
      capture(fn -> assert Mix.Tasks.Muro.Gen.run([]) == :ok end)
    end)
  end

  defp check!(dir) do
    in_dir(dir, fn ->
      capture(fn -> assert Mix.Tasks.Muro.Gen.run(["--check"]) == :ok end)
    end)
  end

  defp check_error(dir) do
    in_dir(dir, fn ->
      assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Gen.run(["--check"]) end
    end).message
  end

  defp cli!(dir, args) do
    in_dir(dir, fn ->
      parent = self()

      out =
        ExUnit.CaptureIO.capture_io(fn ->
          send(parent, {:code, Muro.CLI.main(args)})
        end)

      assert_received {:code, 0}
      out
    end)
  end

  defp in_dir(dir, fun), do: File.cd!(dir, fun)

  defp capture(fun) do
    fun
    |> ExUnit.CaptureIO.capture_io()
    |> String.replace(~r/^==> \S+\n/m, "")
  end

  defp tmp do
    dir = Path.join(System.tmp_dir!(), "muro_native_#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)
    dir
  end
end
