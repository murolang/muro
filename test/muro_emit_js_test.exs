    out = capture_io(fn -> Mix.Tasks.Muro.Emit.run([path, "--backend", "js"]) end)
    assert out =~ mjs
    assert out =~ dts
    source = File.read!(mjs)
    types = File.read!(dts)

    assert source =~ "// generated by muro — do not edit\n"
    assert source =~ "export function plus(n, m)"
    assert source =~ "export function half(n)"
    assert source =~ "plus__w(np, m"
    refute source =~ "plus__w(m, np"
    assert source =~ "0n"
    refute source =~ "IsEven"
    refute source =~ "function half_ok"
    refute types =~ "IsEven"
    assert types =~ "export type Nat = bigint;"
    assert types =~ "export function plus(n: Nat, m: Nat): Nat;"
    assert types =~ "export function half(n: Nat): Nat;"
    assert types =~ "I64 at the host boundary is a signed bigint"
    assert types =~ "BigInt.asIntN(64)"
    refute types =~ "I64 is the unsigned residue"
    assert types =~ "export function muro__data("
    assert types =~ "export function muro__uncons<A>(s: Stream<A>): readonly [A, Stream<A>];"
    assert types =~ "export function muro__canon("
