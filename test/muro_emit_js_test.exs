  # Node warns on stderr when both NO_COLOR and FORCE_COLOR are set.
  # The driver merges stderr into stdout, so that warning would fail a line count.
  defp node(script, dir) do
    System.cmd(@node, [script],
      cd: dir,
      stderr_to_stdout: true,
      env: [{"NO_COLOR", nil}, {"FORCE_COLOR", nil}]
    )
  end

  defp run_example(dir, stem, queries) do
    path = Path.join(dir, stem <> ".muro")

    if not File.regular?(path) do
      File.cp!(Path.join("examples", stem <> ".muro"), path)
    end

    {:ok, [mjs, _dts]} = Muro.emit_js(path)
    {js_names, ex_names, mod} = load_pair(path)

    expected =
      Map.new(queries, fn query ->
        {label(query), eval_ex(query, mod, ex_names)}
      end)

    File.write!(Path.join(dir, "_drv_#{stem}.mjs"), driver(stem, queries, js_names))
    {out, status} = node("_drv_#{stem}.mjs", dir)
    assert status == 0, out

    lines =
      out
      |> String.trim_trailing("\n")
      |> case do
        "" -> []
        text -> String.split(text, "\n")
      end

    assert length(lines) == length(queries)

    queries
    |> Enum.zip(lines)
    |> Map.new(fn {query, line} ->
      name = label(query)

      assert line == Map.fetch!(expected, name),
             "#{stem} #{name}: js #{line} elixir #{expected[name]}\n#{mjs}"

      {name, line}
    end)
  end

  defp driver(stem, queries, js_names) do
    body =
      Enum.map_join(queries, "\n", fn query ->
        "console.log(#{js_query(query, js_names)});"
      end)

    """
    import * as M from "./#{stem}.mjs";
    const C = (v) => M.muro__canon(v);
    function take(s, n) {
      const out = [];
      let cur = s;
      for (let i = 0; i < n; i++) {
        const p = M.muro__uncons(cur);
        out.push(C(p[0]));
        cur = p[1];
      }
      return out.join(",");
    }
    #{body}
    """
  end

  defp js_query({:val, _label, value}, names), do: "C(#{js_val(value, names)})"
  defp js_query({:take, _label, value, n}, names), do: "take(#{js_val(value, names)}, #{n})"

  defp js_query({:replay, _label, source}, names) do
    fun = Map.fetch!(names, source)

    "(function () { const s = M.#{fun}(0n); const a = M.muro__uncons(s); const b = M.muro__uncons(s); const c = M.muro__uncons(a[1]); return C(a[0]) + \",\" + C(b[0]) + \",\" + C(c[0]); })()"
  end

  defp js_val({:call, name, args}, names) do
    inner = Enum.map_join(args, ", ", &js_val(&1, names))
    "M.#{Map.fetch!(names, name)}(#{inner})"
  end

  defp js_val({:nat, n}, _names), do: "#{n}n"
  defp js_val(:tt, _names), do: "null"
  defp js_val({:atom, name}, _names), do: "\"#{name}\""
  defp js_val({:host, :suc}, _names), do: "(x) => x + 1n"
  defp js_val({:host, :id}, _names), do: "(x) => x"

  defp js_val({:data, tag, fields}, names) do
    inner = Enum.map_join(fields, ", ", &js_val(&1, names))
    tail = if inner == "", do: "", else: ", " <> inner
    "M.muro__data(\"#{tag}\"#{tail})"
  end

  defp js_val({:pair, a, b}, names), do: "[#{js_val(a, names)}, #{js_val(b, names)}]"

  defp eval_ex({:val, _label, value}, mod, names), do: canon(ex_val(value, mod, names))

  defp eval_ex({:take, _label, value, n}, mod, names) do
    value
    |> ex_val(mod, names)
    |> Enum.take(n)
    |> Enum.map_join(",", &canon/1)
  end

  defp eval_ex({:replay, _label, source}, mod, names) do
    s = apply(mod, fun_atom(names, source), [0])
    [a] = Enum.take(s, 1)
    [b] = Enum.take(s, 1)
    [c] = s |> Stream.drop(1) |> Enum.take(1)
    Enum.map_join([a, b, c], ",", &canon/1)
  end

  defp ex_val({:call, name, args}, mod, names) do
    apply(mod, fun_atom(names, name), Enum.map(args, &ex_val(&1, mod, names)))
  end

  defp ex_val({:nat, 0}, _mod, _names), do: 0
  defp ex_val({:nat, n}, _mod, _names) when n > 0, do: {:suc, ex_val({:nat, n - 1}, nil, nil)}
  defp ex_val(:tt, _mod, _names), do: :tt
  defp ex_val({:atom, name}, _mod, _names), do: String.to_atom(name)
  defp ex_val({:host, :suc}, _mod, _names), do: fn n -> {:suc, n} end
  defp ex_val({:host, :id}, _mod, _names), do: fn n -> n end

  defp ex_val({:data, tag, fields}, mod, names) do
    xs = Enum.map(fields, &ex_val(&1, mod, names))
    if xs == [], do: String.to_atom(tag), else: List.to_tuple([String.to_atom(tag) | xs])
  end

  defp ex_val({:pair, a, b}, mod, names), do: {ex_val(a, mod, names), ex_val(b, mod, names)}

  defp canon({:suc, n}), do: Integer.to_string(1 + peano_int(n))
  defp canon(n) when is_integer(n), do: Integer.to_string(n)
  defp canon(f) when is_function(f), do: "fn"
  defp canon(%Stream{}), do: "stream"
  defp canon(a) when is_atom(a), do: Atom.to_string(a)

  defp canon(t) when is_tuple(t) do
    case Tuple.to_list(t) do
      [tag | args] when is_atom(tag) ->
        tag = Atom.to_string(tag)
        if args == [], do: tag, else: tag <> "(" <> Enum.map_join(args, ",", &canon/1) <> ")"

      [a, b] ->
        "(" <> canon(a) <> "," <> canon(b) <> ")"
    end
  end

  defp peano_int(0), do: 0
  defp peano_int({:suc, n}), do: 1 + peano_int(n)
  defp peano_int(n) when is_integer(n), do: n

  defp peano_n(0), do: 0
  defp peano_n(n) when n > 0, do: Enum.reduce(1..n, 0, fn _, acc -> {:suc, acc} end)

  defp peano_to_int(n), do: peano_to_int(n, 0)
  defp peano_to_int(0, acc), do: acc
  defp peano_to_int({:suc, n}, acc), do: peano_to_int(n, acc + 1)
  defp peano_to_int(n, acc) when is_integer(n), do: acc + n

  defp load_pair(path) do
    {:ok, book} = Muro.Load.file(path)
    book = Muro.Prelude.for_emit(book)
    {:ok, outline} = Muro.Emit.outline(:js, book, "x")
    js = Map.new(outline.signatures, &{&1.source, &1.name})
    ex = Muro.Emit.elixir_names(book)
    n = System.unique_integer([:positive])
    mod = Module.concat(Muro.JsProbe, "M#{n}")
    {:ok, source} = Muro.emit_file(path, mod)
    [{^mod, _bin}] = Code.compile_string(source)

    on_exit(fn ->
      :code.delete(mod)
      :code.purge(mod)
    end)

    {js, ex, mod}
  end

  defp fun_atom(names, source), do: names |> Map.fetch!(source) |> String.to_atom()
  defp label({_kind, name, _, _}), do: name
  defp label({_kind, name, _}), do: name

  defp nat(n), do: {:nat, n}
  defp data(tag, fields), do: {:data, tag, fields}
  defp pair(a, b), do: {:pair, a, b}

  defp emit_js!(dir, name) do
    path = Path.join(dir, "#{name}.muro")
    out = capture_io(fn -> Mix.Tasks.Muro.Emit.run([path, "--backend", "js"]) end)
    file = Path.join(dir, "#{name}.mjs")
    assert out =~ file
    assert File.regular?(Path.join(dir, "#{name}.d.ts"))
    file
  end

  defp write_book(dir, name, src) do
    File.write!(Path.join(dir, name <> ".muro"), src)
    name
  end

  defp tmp do
    dir = Path.join(System.tmp_dir!(), "muro_js_#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)
    dir
  end
end
