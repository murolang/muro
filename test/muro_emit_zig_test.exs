defmodule Muro.EmitZigTest.Zig do
  @moduledoc false

  defmacro zig_test(name, do: body) do
    extra =
      if is_nil(System.find_executable("zig")) do
        quote do: @tag(skip: "zig is not on PATH")
      else
        quote do: @tag(zig: true)
      end

    quote do
      @tag :zig
      unquote(extra)

      test unquote(name) do
        unquote(body)
      end
    end
  end
end

defmodule Muro.EmitZigTest do
  use ExUnit.Case, async: false

