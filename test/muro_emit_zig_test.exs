    assert source =~
             "pub fn #{step_run}(muro__allocator: muro__std.mem.Allocator) !*const muro__Nat"

    # The run claimed the source spelling, so the parameter takes the next
    # suffix in that space. The generated step is `muro__step_0`.
    assert source =~ "#{step_run}_2: *const muro__Nat"
    refute source =~ "muro__step_0:"
    refute source =~ "fn step0_2("

