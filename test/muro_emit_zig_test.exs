  test "half and plus are a tagged Nat, and evidence is omitted" do
    dir = tmp_dir()
    File.cp!("examples/half_ok.muro", Path.join(dir, "half_ok.muro"))
    source = File.read!(emit_zig!(dir, "half_ok"))

    assert source =~ "// generated by muro — do not edit\n"
    assert source =~ "pub const Nat = union(enum)"
    assert source =~ "pub fn half(allocator: std.mem.Allocator, n: *const Nat) !*const Nat"

    assert source =~
             "pub fn plus(allocator: std.mem.Allocator, n: *const Nat, m: *const Nat) !*const Nat"

    assert source =~ "switch (n.*)"
    assert source =~ "pub fn muro_from_u64(allocator: std.mem.Allocator, k: u64) !*const Nat"
    assert source =~ "pub fn muro_to_u64(n: *const Nat) u64"
    refute source =~ "IsEven"
    refute source =~ "fn half_ok"
  end

  test "run internal is a private function" do
