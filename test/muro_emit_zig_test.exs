    # takes the next spelling in that prefixed namespace.
    assert source =~ "muro_muro_step_0_2: *const Nat"
    refute source =~ "muro_step_0:"
    refute source =~ "fn step0_2("

    File.write!(Path.join(dir, "check.zig"), """
