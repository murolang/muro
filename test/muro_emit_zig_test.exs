    assert zeros =~
             "fn step0(allocator: std.mem.Allocator, env: *const anyopaque, seed: *const anyopaque)"

    refute zeros =~ "head-zeros"
    refute zeros =~ "Always"

    always = File.read!(emit_zig!(dir, "always"))
    refute always =~ "zeros-always-zero"
    refute always =~ "Always"
    refute always =~ "refl"

    nats = File.read!(emit_zig!(dir, "nats"))
