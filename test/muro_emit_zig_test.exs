  test "every refusal is the elaboration's reason and writes nothing" do
    dir = tmp_dir()
    nx = Path.join(dir, "nx_add.muro")
    File.cp!("examples/nx_add.muro", nx)

    assert_raise Mix.Error, ~r/\Ac:machine\z/, fn ->
      Mix.Tasks.Muro.Emit.run([nx, "--backend", "zig"])
    end

    refute File.exists?(Path.join(dir, "nx_add.zig"))

    lam = Path.join(dir, "lam.muro")

    File.write!(lam, """
    def bad : run Π (f : Π (x : Nat) → Nat) → Nat :=
      λ (f : Π (x : Nat) → Nat) → f 0
    """)

    assert_raise Mix.Error, ~r/\Ac:lambda\z/, fn ->
      Mix.Tasks.Muro.Emit.run([lam, "--backend", "zig"])
    end

    refute File.exists?(Path.join(dir, "lam.zig"))

    vec = Path.join(dir, "vec.muro")
    File.cp!("examples/vec.muro", vec)

    assert_raise Mix.Error, ~r/\Ac:lambda\z/, fn ->
      Mix.Tasks.Muro.Emit.run([vec, "--backend", "zig"])
    end

    refute File.exists?(Path.join(dir, "vec.zig"))

    {:ok, machine_book} = Muro.Load.file("examples/nx_add.muro")

    books = [
      {"c:lambda",
       [
         %{
           name: "bad",
           mode: :run,
           type: :nat,
           body: {:lam, :affine, :nat, "n", :ze}
         }
       ]},
      {"c:erased",
       [
         %{
           name: "use",
           mode: :run,
           type: {:pi, :erased, :nat, "n", :nat},
           body: {:lam, :erased, :nat, "n", {:var, "n"}}
         }
       ]},
      {"c:stream",
       [
         %{
           name: "bad",
           mode: :run,
           type: :nat,
           body: {:nu, "X", :nat}
         }
       ]},
      {"c:unsupported",
       [
         %{
           name: "bad",
           mode: :run,
           type: :nat,
           body: {:var, "missing"}
         }
       ]},
      {"c:machine", Muro.Prelude.for_emit(machine_book)}
    ]

    for {reason, book} <- books do
      assert {:error, ^reason} = Muro.IR.elaborate(book)
      assert {:error, ^reason} = Muro.Emit.Zig.render(book, "x")
      assert {:error, ^reason} = Muro.Emit.Rust.render(book, "x")
      assert {:error, ^reason} = Muro.Emit.C.prepare(book, "x")
    end
  end

  zig_test "half, plus, data, indexed data, and the stream drivers compile" do
    dir = tmp_dir()
    File.cp!("examples/half_ok.muro", Path.join(dir, "half_ok.muro"))
    File.cp!("examples/list.muro", Path.join(dir, "list.muro"))
    File.cp!("examples/zeros.muro", Path.join(dir, "zeros.muro"))
    File.cp!("examples/nats.muro", Path.join(dir, "nats.muro"))

    File.write!(Path.join(dir, "data.muro"), """
    data Bool : Type where
      true : Bool
      false : Bool

    data Tok : Nat → Type where
      zed : Π (- n : Nat) → Tok n

    def pick : run Π (b : Bool) → Nat :=
      λ (b : Bool) →
        match b motive (λ _ → Nat)
          | true => 0
          | false => suc 0

    def zero : run Nat := pick true
    def one : run Nat := pick false

    def tok0 : run Tok 0 :=
      zed 0
    """)

    for name <- ~w(half_ok list zeros nats data) do
      emit_zig!(dir, name)
    end

    File.write!(Path.join(dir, "check.zig"), """
    const std = @import("std");
    const half = @import("half_ok.zig");
    const list = @import("list.zig");
    const zeros = @import("zeros.zig");
    const nats = @import("nats.zig");
    const data = @import("data.zig");

    test "closed run" {
        var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
        defer arena.deinit();
        const a = arena.allocator();

        const h = try half.half(a, try half.muro_from_u64(a, 4));
        try std.testing.expectEqual(@as(u64, 2), half.muro_to_u64(h));
        const p = try half.plus(a, try half.muro_from_u64(a, 2), try half.muro_from_u64(a, 3));
        try std.testing.expectEqual(@as(u64, 5), half.muro_to_u64(p));

        try std.testing.expectEqual(@as(u64, 0), data.muro_to_u64(try data.zero(a)));
        try std.testing.expectEqual(@as(u64, 1), data.muro_to_u64(try data.one(a)));
        const tok = try data.tok0(a);
        try std.testing.expect(tok.* == .zed);

        const n = try list.length(a, try list.ones2(a));
        try std.testing.expectEqual(@as(u64, 2), list.muro_to_u64(n));

        const z = try zeros.zeros(a);
        const zp = try z.step(a, z.env, z.seed);
        const zh = zeros.muro_reveal(zeros.Nat, zp.fst);
        try std.testing.expectEqual(@as(u64, 0), zeros.muro_to_u64(zh));
        const zp2 = try z.step(a, z.env, zp.snd);
        const zh2 = zeros.muro_reveal(zeros.Nat, zp2.fst);
        try std.testing.expectEqual(@as(u64, 0), zeros.muro_to_u64(zh2));

        const s = try nats.natsFrom(a, try nats.muro_from_u64(a, 0));
        var seed = s.seed;
        var i: u64 = 0;
        while (i < 4) : (i += 1) {
            const sp = try s.step(a, s.env, seed);
            const sh = nats.muro_reveal(nats.Nat, sp.fst);
            try std.testing.expectEqual(i, nats.muro_to_u64(sh));
            seed = sp.snd;
        }

        try std.testing.expect(arena.reset(.free_all));
    }
    """)

    {out, status} =
      System.cmd(zig!(), ["test", "check.zig"], cd: dir, stderr_to_stdout: true)

    assert status == 0, out
    assert out =~ "All 1 tests passed."
  end

  zig_test "a source run named step0 stays a Nat beside the unfold step" do
    dir = tmp_dir()

    File.write!(Path.join(dir, "step0.muro"), """
    ν Stream (A : Type) : Type where
      uncons : Stream A → A × Stream A

    def step0 : run Nat := suc 0

    def zeros : run Stream Nat :=
      unfold 0 (λ (_ : Nat) → (0, 0))

    def hd : run Π (s : Stream Nat) → Nat :=
      λ (s : Stream Nat) → head s
    """)

    source = File.read!(emit_zig!(dir, "step0"))
    assert source =~ "pub fn step0(allocator: std.mem.Allocator) !*const Nat"
    assert source =~ "fn step0_2("

    File.write!(Path.join(dir, "check.zig"), """
    const std = @import("std");
    const m = @import("step0.zig");

    test "step0" {
        var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
        defer arena.deinit();
        const a = arena.allocator();

        try std.testing.expectEqual(@as(u64, 1), m.muro_to_u64(try m.step0(a)));
        const z = try m.zeros(a);
        try std.testing.expectEqual(@as(u64, 0), m.muro_to_u64(try m.hd(a, z)));
    }
    """)

    {out, status} = System.cmd(zig!(), ["test", "check.zig"], cd: dir, stderr_to_stdout: true)
    assert status == 0, out
    assert out =~ "All 1 tests passed."
  end

  zig_test "a shadowed parameter resolves to the inner binding" do
    dir = tmp_dir()

    File.write!(Path.join(dir, "shadow.muro"), """
    def pick : run Π (x : Nat) → Π (x : Nat) → Nat :=
      λ (x : Nat) → λ (x : Nat) → x

    def third : run Π (x : Nat) → Π (y : Nat) → Π (x : Nat) → Nat :=
      λ (x : Nat) → λ (y : Nat) → λ (x : Nat) → x
    """)

    emit_zig!(dir, "shadow")

    File.write!(Path.join(dir, "check.zig"), """
    const std = @import("std");
    const m = @import("shadow.zig");

    test "shadow" {
        var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
        defer arena.deinit();
        const a = arena.allocator();
        const one = try m.muro_from_u64(a, 1);
        const two = try m.muro_from_u64(a, 2);
        const three = try m.muro_from_u64(a, 3);

        try std.testing.expectEqual(@as(u64, 2), m.muro_to_u64(try m.pick(a, one, two)));
        try std.testing.expectEqual(@as(u64, 3), m.muro_to_u64(try m.third(a, one, two, three)));
    }
    """)

    {out, status} = System.cmd(zig!(), ["test", "check.zig"], cd: dir, stderr_to_stdout: true)
    assert status == 0, out
    assert out =~ "All 1 tests passed."
  end

  zig_test "suc reveals an argument whose type is an alias of Nat" do
    dir = tmp_dir()

    File.write!(Path.join(dir, "alias_nat.muro"), """
    def R : spec Type := Nat
    def inc : run Π (r : R) → R := λ (r : R) → suc r
    def two : run R := inc (inc 0)
    """)

    emit_zig!(dir, "alias_nat")

    File.write!(Path.join(dir, "check.zig"), """
    const std = @import("std");
    const m = @import("alias_nat.zig");

    test "alias nat" {
        var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
        defer arena.deinit();
        const a = arena.allocator();
        const two = m.muro_reveal(m.Nat, try m.two(a));
        try std.testing.expectEqual(@as(u64, 2), m.muro_to_u64(two));
        const n = m.muro_reveal(m.Nat, try m.inc(a, m.muro_erase(try m.muro_from_u64(a, 4))));
        try std.testing.expectEqual(@as(u64, 5), m.muro_to_u64(n));
    }
    """)

    {out, status} = System.cmd(zig!(), ["test", "check.zig"], cd: dir, stderr_to_stdout: true)
