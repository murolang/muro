  defp emit_zig!(dir, name) do
    path = Path.join(dir, "#{name}.muro")
    out = capture_io(fn -> Mix.Tasks.Muro.Emit.run([path, "--backend", "zig"]) end)
    file = Path.join(dir, "#{name}.zig")
    assert out =~ file
    assert File.regular?(file)
    file
  end

  defp tmp_dir do
    dir = Path.join(System.tmp_dir!(), "muro_zig_#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)
    dir
  end

  defp zig! do
    path = System.find_executable("zig")
    assert is_binary(path), "zig not found"
    path
  end
