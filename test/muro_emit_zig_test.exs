  defp forms_book(samples) do
    runs =
      samples
      |> Enum.with_index()
      |> Enum.map_join("\n", fn {name, i} ->
        "def #{name} : run Nat := #{peano(i)}"
      end)

    """
    ν Stream (A : Type) : Type where
      uncons : Stream A → A × Stream A

    def flow : run Stream Nat :=
      unfold 0 (λ (_ : Nat) → (0, 0))

    def hd : run Π (s : Stream Nat) → Nat :=
      λ (s : Stream Nat) → head s

    #{runs}
    """
  end

  defp peano(0), do: "0"
  defp peano(n), do: "suc (" <> peano(n - 1) <> ")"

  defp step_fns(source) do
    ~r/fn (muro__step_\d+)\(/
    |> Regex.scan(source)
    |> Enum.map(fn [_, name] -> name end)
    |> Enum.uniq()
  end

  defp emit_zig!(dir, name) do
    path = Path.join(dir, "#{name}.muro")
    out = capture_io(fn -> Mix.Tasks.Muro.Emit.run([path, "--backend", "zig"]) end)
    file = Path.join(dir, "#{name}.zig")
    assert out =~ file
    assert File.regular?(file)
    file
  end

  defp tmp_dir do
    dir = Path.join(System.tmp_dir!(), "muro_zig_#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)
    dir
  end

  defp zig! do
    path = System.find_executable("zig")
    assert is_binary(path), "zig not found"
    path
  end
