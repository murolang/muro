  test "a fieldless constructor is one static value and an erased argument is dropped" do
    dir = tmp_dir()

    File.write!(Path.join(dir, "data.muro"), """
    data Bool : Type where
      true : Bool
      false : Bool

    data Tok : Nat → Type where
      zed : Π (- n : Nat) → Tok n
      one : Π (- n : Nat) → Nat → Tok n

    def pick : run Π (b : Bool) → Nat :=
      λ (b : Bool) →
        match b motive (λ _ → Nat)
          | true => 0
          | false => suc 0

    def zero : run Nat := pick true
    def no : run Nat := pick false

    def tok0 : run Tok 0 :=
      zed 0

    def drop : run Π (- n : Nat) → Nat :=
      λ (- n : Nat) → 0
    """)

    source = File.read!(emit_zig!(dir, "data"))
    assert source =~ "pub const Bool = union(enum)"
    assert source =~ "muro_true,"
    assert source =~ "const muro_val_Bool_muro_true: Bool = .muro_true;"
    assert source =~ "fn muro_true() *const Bool"
    assert source =~ "const muro_val_Tok_zed: Tok = .zed;"
    assert source =~ "fn zed() *const Tok"
    refute source =~ "fn one("
    assert source =~ "pub fn drop(allocator: std.mem.Allocator) !*const Nat"
    refute source =~ "drop(allocator: std.mem.Allocator, "
  end

  test "a keyword, a primitive, and a taken spelling are renamed" do
    dir = tmp_dir()

    File.write!(Path.join(dir, "names.muro"), """
    data Bool : Type where
      true : Bool
      false : Bool

    def type : run Π (bool : Bool) → Nat :=
      λ (bool : Bool) →
        match bool motive (λ _ → Nat)
          | true => 0
          | false => suc 0

    def u8 : run Nat := 0
    def error : run Nat := 0
    def std : run Nat := 0
    def fn : run Nat := 0
    def Nat : run Nat := suc 0
    def foo-bar : run Nat := 0
    def foo_bar : run Nat := suc 0
    def keep : run Nat := u8
    """)

    source = File.read!(emit_zig!(dir, "names"))
    assert source =~ "pub fn muro_type(allocator: std.mem.Allocator, muro_bool: *const Bool)"
    assert source =~ "pub fn muro_u8("
    assert source =~ "pub fn muro_error("
    assert source =~ "pub fn muro_std("
    assert source =~ "pub fn muro_fn("
    assert source =~ "pub fn muro_Nat("
    assert source =~ "pub fn foo_bar("
    assert source =~ "pub fn foo_bar_2("
    assert source =~ "pub fn keep("
    refute source =~ ~r/(?<![\w])fn type\(/
    refute source =~ ~r/(?<![\w])fn u8\(/
    refute source =~ ~r/(?<![\w])fn std\(/
    refute source =~ ~r/(?<![\w])fn true\(/
  end

  test "a lambda applied on the spot is a local" do
    dir = tmp_dir()

    File.write!(Path.join(dir, "apply_lam.muro"), """
    def id : run Π (n : Nat) → Nat :=
      λ (n : Nat) → (λ (m : Nat) → suc m) n

    def keep : run Π (n : Nat) → Nat :=
