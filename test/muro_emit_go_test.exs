defmodule Muro.EmitGoTest do
  use ExUnit.Case, async: false

  alias Muro.Emit.Go

  test "the header is a generated-file line and the package follows the stem" do
    src = render!("examples/ping.muro")
    assert src =~ ~r/^\/\/ Code generated by muro .+ DO NOT EDIT\.$/m
    assert src =~ "package ping\n"
    assert src =~ "type Ping struct"
    assert src =~ "type IllegalTransitionError struct"
    assert src =~ "func (e *IllegalTransitionError) Unwrap() error"
    refute src =~ "panic("
    refute src =~ "func init("
    assert src =~ "\"errors\""
    assert src =~ "\"fmt\""
    refute src =~ "\"sort\""
    assert render!("examples/ping.muro") == src
  end

  test "a keyed family imports sort and names the package from the stem" do
    src = render!("examples/keyed-slots.muro")
    assert src =~ "package keyed_slots\n"
    assert src =~ "type Slots struct"
    assert src =~ "func NewSlots() *Slots"
    assert src =~ "func (s *Slots) Arrive("
    assert src =~ "func (s *Slots) SkipBelow("
    assert src =~ "func (s *Slots) Revert("
    assert src =~ "\"sort\""
    refute src =~ "sync.Mutex"
    refute src =~ "func (s *Slots) Redeliver"
  end

  test "package names avoid keywords and a bad --package is refused" do
    assert Go.package_of("keyed-slots") == "keyed_slots"
    assert Go.package_of("type") == "type_k"
    assert Go.package_of("go") == "go_k"
    assert Go.package_of("1abc") == "p_1abc"
    assert Go.package_of("Func") == "func_k"
    assert Go.check_package(nil) == :ok
    assert Go.check_package("ping") == :ok
    assert {:error, "go: package name"} = Go.check_package("Type")
    assert {:error, "go: package name"} = Go.check_package("type")
    assert {:error, "go: package name"} = Go.check_package("ping-go")

    src = render!("examples/ping.muro", package: "host")
    assert src =~ "package host\n"
  end

  test "a session named Send does not take the event type" do
    src =
      render_text!("reserve.muro", """
      session Send := recv Nat end
      session String := send Nat end
      """)

    assert src =~ "type Send_2 struct"
    assert src =~ "type String_2 struct"
    assert src =~ "type Send struct"
  end

  test "a jump from one session to another is refused" do
    assert {:error, "go: unsupported protocol"} = render("examples/session-calls.muro")
  end

  test "a book with no session is the same refusal as the state machine" do
    assert {:error, "examples/half_ok.muro has no session to emit"} =
             render("examples/half_ok.muro")

    assert {:error, "go: repr payload"} =
             render_text("repr.muro", """
             repr Nat := integer
             session s := send Nat end
             """)
  end

  test "mix muro.emit --backend go writes the file and refuses the other flags" do
    dir = tmp()
    path = Path.join(dir, "ping.muro")
    File.cp!("examples/ping.muro", path)

    Mix.Tasks.Muro.Emit.run([path, "--backend", "go", "--package", "host"])
    go = Path.join(dir, "ping.go")
    assert File.read!(go) =~ "package host\n"
    assert File.read!(go) =~ ~r/^\/\/ Code generated by muro .+ DO NOT EDIT\.$/m

    assert_raise Mix.Error, ~r/go: package name/, fn ->
      Mix.Tasks.Muro.Emit.run([path, "--backend", "go", "--package", "Type"])
    end

    assert_raise Mix.Error, ~r/--package is only valid with --backend go/, fn ->
      Mix.Tasks.Muro.Emit.run([path, "--backend", "rust", "--package", "host"])
    end

    assert_raise Mix.Error, ~r/--imports is only valid with --backend exunit/, fn ->
      Mix.Tasks.Muro.Emit.run([path, "--backend", "go", "--imports"])
    end

    assert_raise Mix.Error, ~r/--node writes the placement calls/, fn ->
      Mix.Tasks.Muro.Emit.run([path, "--backend", "go", "--node", "a"])
    end
  end

  test "muro gen writes a .go target and checks it" do
    dir = tmp()
    File.mkdir_p!(Path.join(dir, "priv/muro"))
    File.cp!("examples/ping.muro", Path.join(dir, "priv/muro/ping.muro"))
    version = Mix.Tasks.Muro.version()

    File.write!(Path.join(dir, "muro.exs"), """
    [
      muro: "#{version}",
      modules: [
        {"priv/muro/ping.muro", "src/ping.go", [kind: :go]}
      ]
    ]
    """)

    {:ok, manifest} = Muro.Manifest.load(dir)
    assert manifest.modules |> hd() |> Map.get(:kind) == :go
    assert {:ok, ["written src/ping.go"]} = Muro.Gen.generate(manifest, dir, version)
    file = Path.join(dir, "src/ping.go")
    text = File.read!(file)
    assert text =~ "Generated by Muro"
    assert text =~ "Code generated by muro #{version}. DO NOT EDIT."
    assert text =~ "package ping\n"
    assert :ok = Muro.Gen.check(manifest, dir, version)

    bad = Path.join(dir, "bad")
    File.mkdir_p!(Path.join(bad, "priv/muro"))
    File.cp!("examples/ping.muro", Path.join(bad, "priv/muro/ping.muro"))

    File.write!(Path.join(bad, "muro.exs"), """
    [
      muro: "#{version}",
      modules: [
        {"priv/muro/ping.muro", "src/ping.rs", [kind: :go]}
      ]
    ]
    """)

    assert {:error, errors} = Muro.Manifest.load(bad)
    assert errors =~ "must end with .go"
  end

  defp render!(path, opts \\ []) do
    assert {:ok, src} = render(path, opts)
    src
  end

  defp render(path, opts \\ []) do
    case Muro.Load.file(path) do
      {:ok, book} ->
        book = book |> Muro.Prelude.for_emit() |> Muro.Grade.erase_book()
        Go.render(book, path, opts)

      {:error, msg} ->
        {:error, msg}
    end
  end

  defp render_text!(name, text) do
    assert {:ok, src} = render_text(name, text)
    src
  end

  defp render_text(name, text) do
    dir = tmp()
    path = Path.join(dir, name)
    File.write!(path, text)
    render(path)
  end

  defp tmp do
    dir = Path.join(System.tmp_dir!(), "muro-go-unit-#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    dir
  end
end
