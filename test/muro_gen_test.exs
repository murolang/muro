defmodule Muro.GenTest do
  use ExUnit.Case, async: false

  @one "def one : run Nat := suc 0\n"

  @round """
  def round : run Π (n : Nat) → Nat :=
    λ (n : Nat) → n
  def round-ok : evidence {round (suc 0) ≡ suc 0 : Nat} :=
    refl
  def step : run internal Π (n : Nat) → Nat :=
    λ (n : Nat) → suc n
  def step-ok : evidence {step 0 ≡ suc 0 : Nat} :=
    refl
  """

  @plus """
  def plus : run Pi (n : Nat) -> Pi (m : Nat) -> Nat :=
    lam (n : Nat) -> lam (m : Nat) ->
      match n motive (lam _ -> Nat)
        | 0 => m
        | suc np => suc(plus np m)
  """

  test "emit_file uses the given module name" do
    dir = tmp_dir()
    path = write_book(dir, "rounding.muro", @one)

    assert {:ok, source} = Muro.emit_file(path, MyApp.Billing.Rounding)
    assert source =~ "defmodule MyApp.Billing.Rounding do\n"
    refute source =~ "defmodule Rounding do\n"
  end

  test "header round trip" do
    version = Mix.Tasks.Muro.version()
    body = "defmodule One do\nend\n"
    book_hash = Muro.Gen.body_hash("book")
    body_hash = Muro.Gen.body_hash(body)
    file = Muro.Gen.header(version, "priv/muro/one.muro", book_hash, body_hash) <> body

    assert {:ok, header} = Muro.Gen.parse_header(file)
    assert header.version == version
    assert header.book == "priv/muro/one.muro"
    assert header.book_hash == book_hash
    assert header.body_hash == body_hash
    assert header.body == body
    assert Muro.Gen.parse_header(body) == :error
  end

  test "book hash covers the book and its imports, in path order" do
    dir = tmp_dir()
    write_book(dir, "priv/muro/nat.muro", @one)

    write_book(dir, "priv/muro/use.muro", """
    import "nat.muro"
    def two : run Nat := suc one
    """)

    nat = File.read!(Path.join(dir, "priv/muro/nat.muro"))
    use = File.read!(Path.join(dir, "priv/muro/use.muro"))

    payload =
      [
        {"priv/muro/nat.muro", nat},
        {"priv/muro/use.muro", use}
      ]
      |> Enum.sort()
      |> Enum.map(fn {rel, bytes} -> [rel, 0, bytes, 0] end)
      |> IO.iodata_to_binary()

    expected = :crypto.hash(:sha256, payload) |> Base.encode16(case: :lower)
    assert Muro.Gen.book_hash(dir, "priv/muro/use.muro") == expected
    assert Muro.Gen.book_hash(dir, "priv/muro/use.muro") == expected

    write_book(dir, "priv/muro/nat.muro", @one <> "-- touch\n")
    assert Muro.Gen.book_hash(dir, "priv/muro/use.muro") != expected

    write_book(dir, "priv/muro/a.muro", "import \"b.muro\"\ndef a : run Nat := b\n")
    write_book(dir, "priv/muro/b.muro", "import \"a.muro\"\ndef b : run Nat := a\n")
    assert Muro.Gen.book_files(Path.join(dir, "priv/muro/a.muro")) |> length() == 2
    assert Muro.Gen.book_hash(dir, "priv/muro/a.muro") =~ ~r/\A[0-9a-f]{64}\z/
  end

  test "gen writes the manifest module, is byte-stable, and leaves an unchanged file" do
    dir = project()
    version = Mix.Tasks.Muro.version()

    in_dir(dir, fn ->
      assert Mix.Tasks.Muro.Gen.run([]) == :ok
    end)

    target = Path.join(dir, "lib/my_app/billing/rounding.ex")
    content = File.read!(target)

    assert content =~ "defmodule MyApp.Billing.Rounding do\n"
    refute content =~ "defmodule One do\n"

    assert String.starts_with?(
             content,
             "# Generated by Muro #{version} from priv/muro/one.muro (book sha256 "
           )

    assert content =~ "# Do not edit; change the .muro file and run mix muro.gen.\n"
    assert String.ends_with?(content, "\n")
    refute String.ends_with?(content, "\n\n")
    refute content =~ Path.basename(dir)
    assert {:ok, header} = Muro.Gen.parse_header(content)
    assert header.conforms == []
    assert header.book_hash == Muro.Gen.book_hash(dir, "priv/muro/one.muro")
    assert header.body_hash == Muro.Gen.body_hash(header.body)
    refute content =~ "# Conforms to"

    {formatter, _opts} =
      Mix.Tasks.Format.formatter_for_file(target, root: dir)

    # No .formatter.exs: the bytes match Code.format_string!/2.
    formatted =
      content
      |> Code.format_string!()
      |> IO.iodata_to_binary()

    formatted = String.trim_trailing(formatted, "\n") <> "\n"
    assert formatted == content
    assert formatter.(content) == content

    stat = File.stat!(target)
    Process.sleep(1100)

    again =
      in_dir(dir, fn ->
        capture(fn -> Mix.Tasks.Muro.Gen.run([]) end)
      end)

    assert again == "unchanged lib/my_app/billing/rounding.ex\n"
    assert File.read!(target) == content
    assert File.stat!(target).mtime == stat.mtime

    check =
      in_dir(dir, fn ->
        capture(fn -> Mix.Tasks.Muro.Gen.run(["--check"]) end)
      end)

    assert check == "ok\n"
    assert File.stat!(target).mtime == stat.mtime
  end

