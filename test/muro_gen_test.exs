  test "a repr is part of the committed module" do
    dir = repr_project()
    version = Mix.Tasks.Muro.version()

    output =
      in_dir(dir, fn ->
        capture(fn -> Mix.Tasks.Muro.Gen.run([]) end)
      end)

    assert output =~ "written lib/host/repr.ex\n"
    target = Path.join(dir, "lib/host/repr.ex")
    content = File.read!(target)
    assert content =~ "defmodule Host.Repr do\n"
    assert content =~ "def toggle("
    assert content =~ "def decode_entry("
    assert content =~ "def encode_entry("
    assert content =~ "def decode_outcome("
    assert content =~ "@muro_repr_nat_max 1_000_000"
    assert content =~ "Generated by Muro #{version} from priv/muro/repr.muro"

    again =
      in_dir(dir, fn ->
        capture(fn -> Mix.Tasks.Muro.Gen.run([]) end)
      end)

    assert again =~ "unchanged lib/host/repr.ex\n"
    assert File.read!(target) == content

    check =
      in_dir(dir, fn ->
        capture(fn -> Mix.Tasks.Muro.Gen.run(["--check"]) end)
      end)

    assert check == "ok\n"

    {formatter, _} = Mix.Tasks.Format.formatter_for_file(target, root: dir)
    assert formatter.(content) == content

    book = Path.join(dir, "priv/muro/repr.muro")
    File.write!(book, String.replace(File.read!(book), "optional Bool", "nullable Bool"))
    message = check_error(dir)
    assert message =~ "lib/host/repr.ex: stale target; priv/muro/repr.muro changed"
    refute message =~ "hand-edited target"

    File.write!(book, File.read!("examples/repr.muro"))

    in_dir(dir, fn ->
      capture(fn -> Mix.Tasks.Muro.Gen.run([]) end)
    end)

    edited =
      String.replace(File.read!(target), "def decode_entry", "def decode_entry_edited",
        global: false
      )

    File.write!(target, edited)
    message = check_error(dir)
    assert message =~ "lib/host/repr.ex: hand-edited target; priv/muro/repr.muro"
    refute message =~ "stale target"
  end

  defp repr_project do
    dir = tmp_dir()
    File.write!(Path.join(dir, ".formatter.exs"), File.read!(".formatter.exs"))
    write_book(dir, "priv/muro/repr.muro", File.read!("examples/repr.muro"))
    write_manifest(dir, [{"priv/muro/repr.muro", Host.Repr, "lib/host/repr.ex"}])
    dir
  end

  defp generated do
    dir = project()

    in_dir(dir, fn ->
      capture(fn -> Mix.Tasks.Muro.Gen.run([]) end)
    end)

    dir
  end

  defp project do
    dir = tmp_dir()
    write_book(dir, "priv/muro/one.muro", @one)

    write_manifest(dir, [
      {"priv/muro/one.muro", MyApp.Billing.Rounding, "lib/my_app/billing/rounding.ex"}
    ])

    dir
  end

  defp project_with_formatter(formatter) do
    dir = tmp_dir()
    write_book(dir, "priv/muro/plus.muro", @plus)

    if formatter do
      File.write!(Path.join(dir, ".formatter.exs"), formatter)
    end

    write_manifest(dir, [{"priv/muro/plus.muro", MyApp.Plus, "lib/my_app/plus.ex"}])

    in_dir(dir, fn ->
      capture(fn -> Mix.Tasks.Muro.Gen.run([]) end)
    end)

    dir
  end

  defp check_error(dir) do
    in_dir(dir, fn ->
      assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Gen.run(["--check"]) end
    end).message
  end

  defp write_manifest(dir, modules, opts \\ []) do
    version = Keyword.get(opts, :version, Mix.Tasks.Muro.version())

    entries =
      Enum.map_join(modules, "\n", fn {book, module, target} ->
        "    {#{inspect(book)}, #{inspect(module)}, #{inspect(target)}},"
      end)

    File.write!(Path.join(dir, "muro.exs"), """
    [
      muro: "#{version}",
      modules: [
    #{entries}
      ]
    ]
    """)
  end

  defp write_book(dir, rel, source) do
    path = Path.join(dir, rel)
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, source)
    path
  end

  defp in_dir(dir, fun), do: File.cd!(dir, fun)

  defp capture(fun), do: ExUnit.CaptureIO.capture_io(fun)

  defp tmp_dir do
    dir = Path.join(System.tmp_dir!(), "muro_gen_#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)
    dir
  end
end
