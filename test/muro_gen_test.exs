defmodule Muro.GenTest do
  use ExUnit.Case, async: false

  @one "def one : run Nat := suc 0\n"

  @plus """
  def plus : run Pi (n : Nat) -> Pi (m : Nat) -> Nat :=
    lam (n : Nat) -> lam (m : Nat) ->
      match n motive (lam _ -> Nat)
        | 0 => m
        | suc np => suc(plus np m)
  """

  test "emit_file uses the given module name" do
    dir = tmp_dir()
    path = write_book(dir, "rounding.muro", @one)

    assert {:ok, source} = Muro.emit_file(path, MyApp.Billing.Rounding)
    assert source =~ "defmodule MyApp.Billing.Rounding do\n"
    refute source =~ "defmodule Rounding do\n"
  end

  test "header round trip" do
    version = Mix.Tasks.Muro.version()
    body = "defmodule One do\nend\n"
    book_hash = Muro.Gen.body_hash("book")
    body_hash = Muro.Gen.body_hash(body)
    file = Muro.Gen.header(version, "priv/muro/one.muro", book_hash, body_hash) <> body

    assert {:ok, header} = Muro.Gen.parse_header(file)
    assert header.version == version
    assert header.book == "priv/muro/one.muro"
    assert header.book_hash == book_hash
    assert header.body_hash == body_hash
    assert header.body == body
    assert Muro.Gen.parse_header(body) == :error
  end

  test "book hash covers the book and its imports, in path order" do
    dir = tmp_dir()
    write_book(dir, "priv/muro/nat.muro", @one)

    write_book(dir, "priv/muro/use.muro", """
    import "nat.muro"
    def two : run Nat := suc one
    """)

    nat = File.read!(Path.join(dir, "priv/muro/nat.muro"))
    use = File.read!(Path.join(dir, "priv/muro/use.muro"))

    payload =
      [
        {"priv/muro/nat.muro", nat},
        {"priv/muro/use.muro", use}
      ]
      |> Enum.sort()
      |> Enum.map(fn {rel, bytes} -> [rel, 0, bytes, 0] end)
      |> IO.iodata_to_binary()

    expected = :crypto.hash(:sha256, payload) |> Base.encode16(case: :lower)
    assert Muro.Gen.book_hash(dir, "priv/muro/use.muro") == expected
    assert Muro.Gen.book_hash(dir, "priv/muro/use.muro") == expected

    write_book(dir, "priv/muro/nat.muro", @one <> "-- touch\n")
    assert Muro.Gen.book_hash(dir, "priv/muro/use.muro") != expected

    write_book(dir, "priv/muro/a.muro", "import \"b.muro\"\ndef a : run Nat := b\n")
    write_book(dir, "priv/muro/b.muro", "import \"a.muro\"\ndef b : run Nat := a\n")
    assert Muro.Gen.book_files(Path.join(dir, "priv/muro/a.muro")) |> length() == 2
    assert Muro.Gen.book_hash(dir, "priv/muro/a.muro") =~ ~r/\A[0-9a-f]{64}\z/
  end

  test "gen writes the manifest module, is byte-stable, and leaves an unchanged file" do
    dir = project()
    version = Mix.Tasks.Muro.version()

    in_dir(dir, fn ->
      assert Mix.Tasks.Muro.Gen.run([]) == :ok
    end)

    target = Path.join(dir, "lib/my_app/billing/rounding.ex")
    content = File.read!(target)

    assert content =~ "defmodule MyApp.Billing.Rounding do\n"
    refute content =~ "defmodule One do\n"

    assert String.starts_with?(
             content,
             "# Generated by Muro #{version} from priv/muro/one.muro (book sha256 "
           )

    assert content =~ "# Do not edit; change the .muro file and run mix muro.gen.\n"
    assert String.ends_with?(content, "\n")
    refute String.ends_with?(content, "\n\n")
    refute content =~ Path.basename(dir)
    assert {:ok, header} = Muro.Gen.parse_header(content)
    assert header.book_hash == Muro.Gen.book_hash(dir, "priv/muro/one.muro")
    assert header.body_hash == Muro.Gen.body_hash(header.body)

    {formatter, _opts} =
      Mix.Tasks.Format.formatter_for_file(target, root: dir)

    # No .formatter.exs: the bytes match Code.format_string!/2.
    formatted =
      content
      |> Code.format_string!()
      |> IO.iodata_to_binary()

    formatted = String.trim_trailing(formatted, "\n") <> "\n"
    assert formatted == content
    assert formatter.(content) == content

    stat = File.stat!(target)
    Process.sleep(1100)

    again =
      in_dir(dir, fn ->
        capture(fn -> Mix.Tasks.Muro.Gen.run([]) end)
      end)

    assert again == "unchanged lib/my_app/billing/rounding.ex\n"
    assert File.read!(target) == content
    assert File.stat!(target).mtime == stat.mtime

    check =
      in_dir(dir, fn ->
        capture(fn -> Mix.Tasks.Muro.Gen.run(["--check"]) end)
      end)

    assert check == "ok\n"
    assert File.stat!(target).mtime == stat.mtime
  end

  test "a failing book writes nothing, including a later book's target" do
    dir = tmp_dir()
    write_book(dir, "priv/muro/one.muro", @one)

    write_book(dir, "priv/muro/bad.muro", """
    def z : run Nat := 0
    def z : run Nat := suc 0
    """)

    write_manifest(dir, [
      {"priv/muro/one.muro", MyApp.One, "lib/my_app/one.ex"},
      {"priv/muro/bad.muro", MyApp.Bad, "lib/my_app/bad.ex"}
    ])

    decoy = Path.join(dir, "lib/my_app/bad.ex")
    File.mkdir_p!(Path.dirname(decoy))
    File.write!(decoy, "leave me\n")

    error =
      in_dir(dir, fn ->
        assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Gen.run([]) end
      end)

    assert error.message =~ "lib/my_app/bad.ex: priv/muro/bad.muro does not check"
    assert error.message =~ "duplicate name"
    assert error.message =~ "muro.gen wrote nothing"
    refute File.exists?(Path.join(dir, "lib/my_app/one.ex"))
    assert File.read!(decoy) == "leave me\n"
  end

  test "fuel from the manifest is what the checker uses" do
    dir = project()

    File.write!(Path.join(dir, "muro.exs"), """
    [
      muro: "#{Mix.Tasks.Muro.version()}",
      fuel: 5,
      modules: [
        {"priv/muro/one.muro", MyApp.Billing.Rounding, "lib/my_app/billing/rounding.ex"}
      ]
    ]
    """)

    error =
      in_dir(dir, fn ->
        assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Gen.run([]) end
      end)

    assert error.message =~ "does not check"
    assert error.message =~ "out of fuel"
    assert error.message =~ "muro.gen wrote nothing"
    refute File.exists?(Path.join(dir, "lib/my_app/billing/rounding.ex"))
  end

  test "version pin refuses gen and check and writes nothing" do
    dir = tmp_dir()
    write_book(dir, "priv/muro/one.muro", @one)
    write_manifest(dir, [{"priv/muro/one.muro", MyApp.One, "lib/one.ex"}], version: "0.0.1")
    running = Mix.Tasks.Muro.version()

    for args <- [[], ["--check"]] do
      error =
        in_dir(dir, fn ->
          assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Gen.run(args) end
        end)

      assert error.message =~ "manifest says 0.0.1"
      assert error.message =~ "running #{running}"
    end

    refute File.exists?(Path.join(dir, "lib/one.ex"))
  end

  test "--check reports a book that does not check" do
    dir = generated()
    version = Mix.Tasks.Muro.version()

    File.write!(Path.join(dir, "muro.exs"), """
    [
      muro: "#{version}",
      fuel: 5,
      modules: [
        {"priv/muro/one.muro", MyApp.Billing.Rounding, "lib/my_app/billing/rounding.ex"}
      ]
    ]
    """)

    message = check_error(dir)
    assert message =~ "lib/my_app/billing/rounding.ex: priv/muro/one.muro does not check"
    assert message =~ "out of fuel"
    refute message =~ "stale target"
    refute message =~ "hand-edited target"
    refute message =~ "missing target"
  end

  test "--check reports a missing target" do
    dir = generated()
    File.rm!(Path.join(dir, "lib/my_app/billing/rounding.ex"))

    message = check_error(dir)

    assert message =~
             "lib/my_app/billing/rounding.ex: missing target for priv/muro/one.muro"

    refute message =~ "stale target"
  end

  test "--check reports a stale target" do
    dir = generated()
    book = Path.join(dir, "priv/muro/one.muro")
    File.write!(book, File.read!(book) <> "-- touch\n")

    message = check_error(dir)
    assert message =~ "lib/my_app/billing/rounding.ex: stale target; priv/muro/one.muro changed"
    refute message =~ "hand-edited target"
    refute message =~ "does not check"
  end

  test "--check reports a hand-edited target" do
    dir = generated()
    target = Path.join(dir, "lib/my_app/billing/rounding.ex")
    File.write!(target, String.replace(File.read!(target), "def one", "def one_edited"))

    message = check_error(dir)
    assert message =~ "lib/my_app/billing/rounding.ex: hand-edited target; priv/muro/one.muro"
    refute message =~ "stale target"
    refute message =~ "does not check"
  end

  test "--check reports a target whose header was removed" do
    dir = generated()
    target = Path.join(dir, "lib/my_app/billing/rounding.ex")
    {:ok, header} = Muro.Gen.parse_header(File.read!(target))
    File.write!(target, header.body)

    message = check_error(dir)
    assert message =~ "lib/my_app/billing/rounding.ex: differs from what priv/muro/one.muro emits"
    refute message =~ "stale target"
    refute message =~ "hand-edited target"
  end

  test "--check reports a consistent header whose body is not what the book emits" do
    dir = generated()
    target = Path.join(dir, "lib/my_app/billing/rounding.ex")
    {:ok, header} = Muro.Gen.parse_header(File.read!(target))
    body = header.body <> "# kept\n"

    File.write!(
      target,
      Muro.Gen.header(
        header.version,
        header.book,
        header.book_hash,
        Muro.Gen.body_hash(body)
      ) <> body
    )

    message = check_error(dir)
    assert message =~ "lib/my_app/billing/rounding.ex: differs from what priv/muro/one.muro emits"
    refute message =~ "stale target"
    refute message =~ "hand-edited target"
    refute message =~ "header says Muro"
  end

  test "--check reports a header from a different muro version" do
    dir = generated()
    running = Mix.Tasks.Muro.version()
    target = Path.join(dir, "lib/my_app/billing/rounding.ex")
    {:ok, header} = Muro.Gen.parse_header(File.read!(target))

    File.write!(
      target,
      Muro.Gen.header("0.0.1", header.book, header.book_hash, header.body_hash) <> header.body
    )

    message = check_error(dir)

    assert message =~
             "lib/my_app/billing/rounding.ex: header says Muro 0.0.1, running #{running}, from priv/muro/one.muro"

    refute message =~ "differs from what"
    refute message =~ "stale target"
    refute message =~ "hand-edited target"
  end

  test "formats with the project's .formatter.exs" do
    plain = project_with_formatter(nil)
    narrow = project_with_formatter("[line_length: 10]\n")

    plain_src = File.read!(Path.join(plain, "lib/my_app/plus.ex"))
    narrow_src = File.read!(Path.join(narrow, "lib/my_app/plus.ex"))

    assert plain_src != narrow_src

    {formatter, opts} =
      Mix.Tasks.Format.formatter_for_file(Path.join(narrow, "lib/my_app/plus.ex"), root: narrow)

    assert Keyword.get(opts, :line_length) == 10
    assert formatter.(narrow_src) == narrow_src
    refute narrow_src =~ Path.basename(narrow)
  end

  test "init writes the manifest, the directory, and the agent note" do
    dir = tmp_dir()
    version = Mix.Tasks.Muro.version()

    output =
      in_dir(dir, fn ->
        capture(fn -> Mix.Tasks.Muro.Init.run([]) end)
      end)

    assert output =~ "created muro.exs"
    assert output =~ "created priv/muro/"
    assert output =~ "AGENTS.md or similar"

    assert output =~
             "Generated files are not edited by hand. The .muro file is the source. Run mix muro.gen after changing it."

    refute File.exists?(Path.join(dir, "AGENTS.md"))
    assert File.dir?(Path.join(dir, "priv/muro"))

    source = File.read!(Path.join(dir, "muro.exs"))
    assert source == Muro.Init.manifest_source(version)
    assert source =~ ~s(muro: "#{version}")

    assert source =~
             ~s(# {"priv/muro/rounding.muro", MyApp.Billing.Rounding, "lib/my_app/billing/rounding.ex"})

    assert {:ok, manifest} = Muro.Manifest.load(dir)
    assert manifest.modules == []
    assert manifest.version == version

    original = source

    error =
      in_dir(dir, fn ->
        assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Init.run([]) end
      end)

    assert error.message =~ "refusing to overwrite an existing manifest: muro.exs"
    assert File.read!(Path.join(dir, "muro.exs")) == original
  end

  test "init --ci github writes the pinned archive workflow and refuses to overwrite it" do
    dir = tmp_dir()
    version = Mix.Tasks.Muro.version()

    in_dir(dir, fn ->
      capture(fn -> Mix.Tasks.Muro.Init.run(["--ci", "github"]) end)
    end)

    workflow = Path.join(dir, ".github/workflows/muro.yml")
    source = File.read!(workflow)
    assert source == Muro.Init.workflow(version)
    assert source =~ "erlef/setup-beam@v1"
    assert source =~ ~s(elixir-version: "1.20.4")
    assert source =~ ~s(otp-version: "29.1")
    assert source =~ "mix archive.install hex muro #{version} --force"
    assert source =~ "mix muro.gen --check"
    refute source =~ "archive.install github"

    error =
      in_dir(dir, fn ->
        assert_raise Mix.Error, fn -> Mix.Tasks.Muro.Init.run(["--ci", "github"]) end
      end)

    assert error.message =~ "muro.exs"
    assert File.read!(workflow) == source
  end

