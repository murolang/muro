defmodule Muro.Gen do
  @moduledoc """
  Write the modules named by a `Muro.Manifest` and compare them to
  what the books emit.

  Each target starts with two comment lines, and one more line per
  package the book loaded. The first names the running Muro version,
  the book path relative to the project root (`/` separators), the
  book sha256, and the body sha256. Each package line is
  `# Conforms to <name> <version> (sha256 <hash>).`. The next line
  says to change the `.muro` file and run `mix muro.gen`. A book
  that imports no package keeps the two lines and nothing between
  them. The body is everything after the "Do not edit" line. The
  body hash is the sha256 of that body, including its single
  trailing newline.

  The book hash is the lowercase hex sha256 of one concatenation.
  The files are the book and every file it imports, directly or
  through another import, including `pkg:` imports under
  `muro_deps/` and `std:` books. Each path is included once; a cycle
  includes each file once. A file that does not parse contributes its
  own bytes and no further imports. A missing import is omitted. The
  prelude is not part of the hash, and neither is `muro.lock`: the
  version pin covers the checker, the emitter, the prelude, and the
  standard library, and the conforms line covers the package version. A
  `std:` book is still hashed, under `std/<file>`, so the hash does
  not depend on where the compiler is installed and changes when that
  book changes. Paths are relative to the project root, with `/`
  separators, sorted lexicographically. An import outside the project
  is a `..` path from that root. A package file is
  `muro_deps/<name>/<path>`. Each file contributes its relative
  path, a zero byte, its bytes, and a zero byte.

  The module name is the manifest's alias. An `:elixir` entry calls
  `Muro.emit_file/3`. An `:exunit` entry calls `Muro.emit_exunit/3`.
  A `:fsm` entry calls `Muro.emit_fsm/3`. A `:c` entry calls
  `Muro.Emit.C.prepare/2` and writes the `.c` target and the `.h`
  beside it. A `:rust` entry calls `Muro.Emit.Rust.render/2`. A
  `:zig` entry calls `Muro.Emit.Zig.render/2`. An `:asm` entry calls
  `Muro.Emit.Asm.render/2`. The stem passed to those emitters is the
  book basename.
  The Elixir bytes are formatted with the project's `.formatter.exs`
  when that file exists (`Mix.Tasks.Format.formatter_for_file/2`),
  and with `Code.format_string!/2` otherwise. `.ex` and `.exs` are
  formatted even when the formatter inputs do not list the file. The
  header is comments, so formatting does not rewrite it. `:c`,
  `:rust`, `:zig`, and `:asm` are not formatted. The body hash is the
  emitter's text. There is no timestamp and no absolute path.

  The header comment is `#` for Elixir, `//` for C, Rust, Zig, and the
  C header, and `@` for Cortex-M assembly. The words of the two
  lines are the same.

  An ExUnit entry's body lists skipped equations in a comment. That
  comment is part of the body hash. `generate/3` prints one
  `skipped` line per skip after the target's `written` or `unchanged`
  line. `check/3` does not print skips; a change to the skipped set
  changes the book, so the target is stale.
  """

  @first ~r/\A(# |\/\/ |@ )Generated by Muro (\S+) from (.+) \(book sha256 ([0-9a-f]{64}), body sha256 ([0-9a-f]{64})\)\.\z/
  @do_not "Do not edit; change the .muro file and run mix muro.gen."

  @doc """
  The two header lines, including the newline after the second line.

  `prefix` is `# ` (the default), `// `, or `@ `.
  """
  def header(version, book, book_hash, body_hash, lines \\ [], prefix \\ "# ")
      when is_binary(version) and is_binary(book) and is_binary(book_hash) and
             is_binary(body_hash) and is_list(lines) and is_binary(prefix) do
    first =
      "#{prefix}Generated by Muro #{version} from #{book} (book sha256 #{book_hash}, body sha256 #{body_hash}).\n"

    middle =
      Enum.map_join(lines, fn
        "conforms to " <> rest -> "#{prefix}Conforms to " <> rest <> ".\n"
      end)

    first <> middle <> prefix <> @do_not <> "\n"
  end

  @doc """
  `{:ok, header}` when `content` starts with `header/4` or `header/5`.
  `:error` when the header is missing or altered. `header.body` is
  every byte after the "Do not edit" line. `header.conforms` is the
  package lines between the first line and that one.
  """
  def parse_header(content) when is_binary(content) do
    with {:ok, prefix, version, book, book_hash, body_hash, rest} <- take_first(content),
         {:ok, conforms, rest} <- take_conforms(rest, [], prefix),
         {:ok, body} <- take_do_not(rest, prefix) do
      {:ok,
       %{
         version: version,
         book: book,
         book_hash: book_hash,
         body_hash: body_hash,
         conforms: conforms,
         body: body,
         prefix: prefix
       }}
    else
      _other -> :error
    end
  end

  defp take_first(content) do
    case split_line(content) do
      {line, rest} ->
        case Regex.run(@first, line) do
          [_, prefix, version, book, book_hash, body_hash] ->
            {:ok, prefix, version, book, book_hash, body_hash, rest}

          _other ->
            :error
        end

      :error ->
        :error
    end
  end

  defp take_conforms(rest, acc, prefix) do
    case split_line(rest) do
      {line, more} ->
        needle = prefix <> "Conforms to "

        if String.starts_with?(line, needle) do
          case Regex.run(
                 ~r/\A(\S+) (\S+) \(sha256 ([0-9a-f]{64})\)\.\z/,
                 String.replace_prefix(line, needle, "")
               ) do
            [_, package, version, sha] ->
              row = %{package: package, version: version, sha256: sha}
              take_conforms(more, acc ++ [row], prefix)

            _other ->
              {:ok, acc, rest}
          end
        else
          {:ok, acc, rest}
        end

      :error ->
        {:ok, acc, rest}
    end
  end

  defp take_do_not(rest, prefix) do
    expect = prefix <> @do_not

    case split_line(rest) do
      {line, body} when line == expect -> {:ok, body}
      _other -> :error
    end
  end

  defp split_line(content) do
    case :binary.split(content, "\n") do
      [line, rest] -> {line, rest}
      _other -> :error
    end
  end

  @doc "Lowercase hex sha256 of a target body."
  def body_hash(body) when is_binary(body), do: Muro.Hash.sha256(body)

  @doc """
  Lowercase hex sha256 of the book at `book_rel` and the files it
  imports. See the module docs for the byte layout.
  """
  def book_hash(root, book_rel) when is_binary(root) and is_binary(book_rel) do
    root = Path.expand(root)
    absolute = Path.expand(book_rel, root)

    absolute
    |> files_under(root)
    |> Enum.map(&hash_entry(&1, root))
    |> Muro.Hash.files()
  end

  # A library id is not on disk. Its hash path is `std/<file>`.
  defp hash_entry("std:" <> name, _root) do
    {:ok, bytes} = Muro.Std.source(name)
    {"std/" <> name, bytes}
  end

  defp hash_entry(file, root) do
    {relative_slash(root, file), File.read!(file)}
  end

  @doc """
  Absolute paths of the book and every file it imports. Each path
  appears once. Discovery order, not the hash order. `pkg:` imports
  are resolved from the nearest ancestor that contains `muro.exs` or
  `mix.exs`.
  """
  def book_files(path) when is_binary(path) do
    path = Path.expand(path)
    files_under(path, Muro.Manifest.find_root(path))
  end

  defp files_under(path, root) do
    {files, _seen} = walk(path, MapSet.new(), [], root)
    Enum.reverse(files)
  end

  @doc """
  Check every book, then write every target.

  `{:ok, lines}` is one `written` or `unchanged` line per target,
  followed by that target's `conforms to` lines indented by two
  spaces. An ExUnit target then adds one `skipped` line per skipped
  equation. An unchanged target is not opened for writing.
  `{:error, message}` means at least one book failed; nothing was
  written.
  """
  def generate(%Muro.Manifest{} = manifest, root, version)
      when is_binary(root) and is_binary(version) do
    root = Path.expand(root)

    with :ok <- reject_failing_books(manifest, root) do
      case render_all(manifest, root, version) do
        {:ok, files} -> {:ok, Enum.flat_map(files, &write_target(root, &1))}
        {:error, message} -> {:error, message <> "\nmuro.gen wrote nothing"}
      end
    end
  end

  @doc """
  Compare every target to its book. Writes nothing.

  `:ok` when every book checks and every target is the bytes `generate/3`
  would leave in place. `{:error, message}` lists every problem.
  """
  def check(%Muro.Manifest{} = manifest, root, version)
      when is_binary(root) and is_binary(version) do
    root = Path.expand(root)

    problems =
      Enum.flat_map(manifest.modules, fn entry ->
        problems_for(entry, root, version, manifest.fuel)
      end)

    if problems == [] do
      :ok
    else
      {:error, Enum.join(problems, "\n")}
    end
  end

  defp reject_failing_books(manifest, root) do
    failures =
      Enum.flat_map(manifest.modules, fn entry ->
        case check_book(entry, root, manifest.fuel) do
          :ok -> []
          {:error, message} -> [does_not_check(entry, message)]
        end
      end)

    if failures == [] do
      :ok
    else
      {:error, Enum.join(failures, "\n") <> "\nmuro.gen wrote nothing"}
    end
  end

  defp render_all(manifest, root, version) do
    Enum.reduce_while(manifest.modules, {:ok, []}, fn entry, {:ok, acc} ->
      case render(root, entry, version, manifest.fuel) do
        {:ok, contents, notes} -> {:cont, {:ok, acc ++ [{entry, contents, notes}]}}
        {:error, message} -> {:halt, {:error, does_not_check(entry, message)}}
      end
    end)
  end

  defp render(root, entry, version, fuel) do
    case Map.get(entry, :kind, :elixir) do
      kind when kind in [:c, :rust, :zig, :asm] ->
        render_native(root, entry, version, fuel, kind)

      _kind ->
        render_elixir(root, entry, version, fuel)
    end
  end

  defp render_elixir(root, entry, version, fuel) do
    path = Muro.Manifest.book_path(root, entry)

    with {:ok, source, skips} <- emit_entry(root, entry, fuel),
         {:ok, lines} <- Muro.conforms(path, conform_opts(entry, root, fuel)) do
      file = settle(root, entry, version, format_elixir(source, entry.target, root), 3, lines)

      if coherent?(file, root, entry, version, lines) do
        {:ok, [%{rel: entry.target, contents: file}], {lines, skips}}
      else
        {:error, "generated header does not describe #{entry.target}"}
      end
    end
  end

  defp render_native(root, entry, version, fuel, kind) do
    path = Muro.Manifest.book_path(root, entry)
    stem = Path.basename(entry.book, ".muro")
    prefix = comment_prefix(kind)

    with {:ok, book} <- native_book(path, fuel, root),
         {:ok, parts} <- native_parts(entry, kind, book, stem),
         {:ok, lines} <- Muro.conforms(path, conform_opts(entry, root, fuel)) do
      book_sha = book_hash(root, entry.book)

      files =
        Enum.map(parts, fn {rel, body} ->
          body = ensure_newline(body)

          %{
            rel: rel,
            contents:
              header(version, entry.book, book_sha, body_hash(body), lines, prefix) <> body
          }
        end)

      if Enum.all?(files, &coherent?(&1.contents, root, entry, version, lines)) do
        {:ok, files, {lines, []}}
      else
        {:error, "generated header does not describe #{entry.target}"}
      end
    end
  end

  defp native_book(path, fuel, root) do
    with {:ok, book} <- Muro.Load.file(path, fuel: fuel, root: root) do
      {:ok, Muro.Prelude.for_emit(book)}
    end
  end

  defp native_parts(entry, :c, book, _stem) do
    # The header is named from the target (`src/rounding.c` writes
    # `rounding.h`). The book's stem would include a different file.
    stem = entry.target |> Path.rootname() |> Path.basename()

    case Muro.Emit.C.prepare(book, stem) do
      {:ok, header, source, _sigs} ->
        {:ok, [{entry.target, source}, {header_rel(entry.target), header}]}

      {:error, _} = err ->
        err
    end
  end

  defp native_parts(entry, :rust, book, stem) do
    case Muro.Emit.Rust.render(book, stem) do
      {:ok, source} -> {:ok, [{entry.target, source}]}
      {:error, _} = err -> err
    end
  end

  defp native_parts(entry, :zig, book, stem) do
    case Muro.Emit.Zig.render(book, stem) do
      {:ok, source} -> {:ok, [{entry.target, source}]}
      {:error, _} = err -> err
    end
  end

  defp native_parts(entry, :asm, book, stem) do
    case Muro.Emit.Asm.render(book, stem) do
      {:ok, source} -> {:ok, [{entry.target, source}]}
      {:error, _} = err -> err
    end
  end

  defp comment_prefix(:asm), do: "@ "
  defp comment_prefix(_kind), do: "// "

  defp header_rel(target), do: Path.rootname(target) <> ".h"

  defp emit_entry(root, entry, fuel) do
    path = Muro.Manifest.book_path(root, entry)

    case Map.get(entry, :kind, :elixir) do
      :exunit ->
        opts = [
          fuel: fuel,
          root: root,
          book: entry.book,
          imports: Map.get(entry, :imports, false)
        ]

        opts =
          case Map.get(entry, :impl) do
            nil -> opts
            impl -> Keyword.put(opts, :impl, impl)
          end

        case Muro.emit_exunit(path, entry.module, opts) do
          {:ok, %{source: source, skips: skips}} -> {:ok, source, skips}
          {:error, message} -> {:error, message}
        end

      :fsm ->
        case Muro.emit_fsm(path, entry.module, fuel: fuel, root: root, book: entry.book) do
          {:ok, source} -> {:ok, source, []}
          {:error, message} -> {:error, message}
        end

      _kind ->
        case Muro.emit_file(path, entry.module, fuel: fuel, root: root) do
          {:ok, source} -> {:ok, source, []}
          {:error, message} -> {:error, message}
        end
    end
  end

  defp coherent?(file, root, entry, version, lines) do
    case parse_header(file) do
      {:ok, header} ->
        header.version == version and header.book == entry.book and
          header.book_hash == book_hash(root, entry.book) and
          header.body_hash == body_hash(header.body) and same_conforms?(header, lines)

      :error ->
        false
    end
  end

  defp same_conforms?(header, lines) do
    Enum.map(header.conforms, fn row ->
      "conforms to #{row.package} #{row.version} (sha256 #{row.sha256})"
    end) == lines
  end

  defp settle(root, entry, version, body, 0, lines) do
    assemble(root, entry, version, body, lines)
  end

  defp settle(root, entry, version, body, left, lines) do
    file = assemble(root, entry, version, body, lines)
    formatted = format_elixir(file, entry.target, root)

    case parse_header(formatted) do
      {:ok, %{body: ^body}} -> file
      {:ok, %{body: next}} -> settle(root, entry, version, next, left - 1, lines)
      :error -> file
    end
  end

  defp assemble(root, entry, version, body, lines) do
    header(version, entry.book, book_hash(root, entry.book), body_hash(body), lines) <> body
  end

  defp write_target(root, {entry, files, {lines, skips}}) do
    Enum.flat_map(Enum.with_index(files), fn {%{rel: rel, contents: contents}, index} ->
      path = Path.expand(rel, root)

      status =
        if File.regular?(path) and File.read!(path) == contents do
          "unchanged #{rel}"
        else
          File.mkdir_p!(Path.dirname(path))
          File.write!(path, contents)
          "written #{rel}"
        end

      extra =
        if index == 0 do
          Enum.map(lines, fn line -> "  " <> line end) ++ Enum.map(skips, &skip_line(entry, &1))
        else
          []
        end

      [status | extra]
    end)
  end

  defp skip_line(entry, skip) do
    "skipped #{entry.target}: #{skip.name} (#{skip.file}:#{skip.line}): #{skip.reason}"
  end

  defp problems_for(entry, root, version, fuel) do
    case check_book(entry, root, fuel) do
      :ok ->
        target_problems(entry, root, version, fuel, true)

      {:error, message} ->
        [does_not_check(entry, message) | target_problems(entry, root, version, fuel, false)]
    end
  end

  defp check_book(entry, root, fuel) do
    Muro.check_file(Muro.Manifest.book_path(root, entry), conform_opts(entry, root, fuel))
  end

  # An exunit entry may be a param library. The loader then checks the
  # params as assumptions. An elixir entry never passes that option.
  defp conform_opts(entry, root, fuel) do
    opts = [fuel: fuel, root: root]
    if Map.get(entry, :kind) == :exunit, do: Keyword.put(opts, :params, :open), else: opts
  end

  defp target_problems(entry, root, version, fuel, book_ok?) do
    Enum.flat_map(output_rels(entry), fn rel ->
      path = Path.expand(rel, root)

      if File.regular?(path) do
        classify(File.read!(path), rel, entry, root, version, fuel, book_ok?)
      else
        ["#{rel}: missing target for #{entry.book}"]
      end
    end)
  end

  defp output_rels(entry) do
    case Map.get(entry, :kind, :elixir) do
      :c -> [entry.target, header_rel(entry.target)]
      _kind -> [entry.target]
    end
  end

  defp classify(content, rel, entry, root, version, fuel, book_ok?) do
    case parse_header(content) do
      :error ->
        differs_message(content, rel, entry, root, version, fuel, book_ok?)

      {:ok, header} ->
        version_problem =
          if header.version == version do
            []
          else
            [
              "#{rel}: header says Muro #{header.version}, running #{version}, from #{entry.book}"
            ]
          end

        current = book_hash(root, entry.book)

        version_problem ++
          hash_problems(content, header, current, rel, entry, root, version, fuel, book_ok?)
    end
  end

  defp hash_problems(content, header, current, rel, entry, root, version, fuel, book_ok?) do
    cond do
      header.book != entry.book ->
        ["#{rel}: differs from what #{entry.book} emits"]

      header.book_hash != current ->
        [
          "#{rel}: stale target; #{entry.book} changed (book sha256 #{header.book_hash}, current #{current})"
        ]

      body_hash(header.body) != header.body_hash ->
        [
          "#{rel}: hand-edited target; #{entry.book} is unchanged and the body no longer matches its recorded sha256"
        ]

      header.version == version and book_ok? ->
        differs_message(content, rel, entry, root, version, fuel, true)

      true ->
        []
    end
  end

  defp differs_message(content, rel, entry, root, version, fuel, true) do
    case render(root, entry, version, fuel) do
      {:ok, files, _notes} ->
        case Enum.find(files, &(&1.rel == rel)) do
          %{contents: ^content} -> []
          _other -> ["#{rel}: differs from what #{entry.book} emits"]
        end

      _other ->
        ["#{rel}: differs from what #{entry.book} emits"]
    end
  end

  defp differs_message(_content, _rel, _entry, _root, _version, _fuel, false), do: []

  defp does_not_check(entry, message) do
    "#{entry.target}: #{entry.book} does not check\n#{message}"
  end

  defp format_elixir(source, target, root) do
    formatted =
      if File.regular?(Path.join(root, ".formatter.exs")) do
        {formatter, _opts} =
          Mix.Tasks.Format.formatter_for_file(Path.join(root, target), root: root)

        formatter.(source)
      else
        source |> Code.format_string!() |> IO.iodata_to_binary()
      end

    ensure_newline(IO.iodata_to_binary(formatted))
  end

  defp ensure_newline(binary) do
    String.trim_trailing(binary, "\n") <> "\n"
  end

  defp walk("std:" <> name = id, seen, acc, root) do
    cond do
      MapSet.member?(seen, id) ->
        {acc, seen}

      true ->
        case Muro.Std.source(name) do
          :error ->
            {acc, seen}

          {:ok, bytes} ->
            seen = MapSet.put(seen, id)
            acc = [id | acc]
            follow_source(id, bytes, seen, acc, root)
        end
    end
  end

  defp walk(path, seen, acc, root) do
    cond do
      MapSet.member?(seen, path) ->
        {acc, seen}

      not File.regular?(path) ->
        {acc, seen}

      true ->
        seen = MapSet.put(seen, path)
        acc = [path | acc]
        follow_imports(path, seen, acc, root)
    end
  end

  defp follow_imports(path, seen, acc, root) do
    case File.read(path) do
      {:ok, source} -> follow_source(path, source, seen, acc, root)
      {:error, _reason} -> {acc, seen}
    end
  end

  defp follow_source(path, source, seen, acc, root) do
    case Muro.Parser.parse(source) do
      {:ok, book} ->
        Enum.reduce(import_paths(book, path, root), {acc, seen}, fn next, {acc, seen} ->
          walk(next, seen, acc, root)
        end)

      {:error, _message} ->
        {acc, seen}
    end
  end

  defp import_paths(book, path, root) do
    dir = if Muro.Std.std_id?(path), do: path, else: Path.dirname(path)

    Enum.flat_map(book, fn entry ->
      case entry do
        %{kind: :import, path: rel} when is_binary(rel) ->
          case Muro.Load.classify_import(rel) do
            {:pkg, name, pkg_path} when is_binary(root) ->
              [Path.join([root, "muro_deps", name | String.split(pkg_path, "/")])]

            {:std, name} ->
              [Muro.Std.id(name)]

            :relative ->
              if Muro.Std.std_id?(path) do
                case Muro.Std.relative(path, rel) do
                  {:ok, name} -> [Muro.Std.id(name)]
                  :escape -> []
                end
              else
                [Path.expand(rel, dir)]
              end

            _other ->
              []
          end

        _other ->
          []
      end
    end)
  end

  @doc """
  `path` relative to `root`, with `/` separators. A path outside
  `root` starts with `..`. The result is never absolute.
  """
  def relative_path(root, path) when is_binary(root) and is_binary(path) do
    relative_slash(root, path)
  end

  defp relative_slash(root, path) do
    root_parts = Path.split(Path.expand(root))
    path_parts = Path.split(Path.expand(path))
    {root_rest, path_rest} = drop_common(root_parts, path_parts)

    case List.duplicate("..", length(root_rest)) ++ path_rest do
      [] -> "."
      parts -> Enum.join(parts, "/")
    end
  end

  defp drop_common([same | root], [same | path]), do: drop_common(root, path)
  defp drop_common(root, path), do: {root, path}
end
