defmodule Muro.Gen do
  @moduledoc """
  Write the modules named by a `Muro.Manifest` and compare them to
  what the books emit.

  Each target starts with two comment lines. The first names the
  running Muro version, the book path relative to the project root
  (`/` separators), the book sha256, and the body sha256. The second
  says to change the `.muro` file and run `mix muro.gen`. The body
  is everything after those two lines. The body hash is the sha256
  of that body, including its single trailing newline.

  The book hash is the lowercase hex sha256 of one concatenation.
  The files are the book and every file it imports, directly or
  through another import. Each path is included once; a cycle
  includes each file once. A file that does not parse contributes
  its own bytes and no further imports. A missing import is omitted.
  The prelude is not part of the hash: the version pin covers the
  checker and the emitter. Paths are relative to the project root,
  with `/` separators, sorted lexicographically. An import outside
  the project is a `..` path from that root. Each file contributes
  its relative path, a zero byte, its bytes, and a zero byte.

  The module name is the manifest's alias. An `:elixir` entry calls
  `Muro.emit_file/3`. An `:exunit` entry calls `Muro.emit_exunit/3`.
  The bytes are formatted with the project's `.formatter.exs` when
  that file exists (`Mix.Tasks.Format.formatter_for_file/2`), and with
  `Code.format_string!/2` otherwise. `.ex` and `.exs` are formatted
  even when the formatter inputs do not list the file. The header is
  comments, so formatting does not rewrite it. There is no timestamp
  and no absolute path.

  An ExUnit entry's body lists skipped equations in a comment. That
  comment is part of the body hash. `generate/3` prints one
  `skipped` line per skip after the target's `written` or `unchanged`
  line. `check/3` does not print skips; a change to the skipped set
  changes the book, so the target is stale.
  """

  @header ~r/\A# Generated by Muro (\S+) from (.+) \(book sha256 ([0-9a-f]{64}), body sha256 ([0-9a-f]{64})\)\.\n# Do not edit; change the \.muro file and run mix muro\.gen\.\n/

  @doc """
  The two header lines, including the newline after the second line.
  """
  def header(version, book, book_hash, body_hash)
      when is_binary(version) and is_binary(book) and is_binary(book_hash) and
             is_binary(body_hash) do
    "# Generated by Muro #{version} from #{book} (book sha256 #{book_hash}, body sha256 #{body_hash}).\n" <>
      "# Do not edit; change the .muro file and run mix muro.gen.\n"
  end

  @doc """
  `{:ok, header}` when `content` starts with `header/4`. `:error`
  when the header is missing or altered. `header.body` is every
  byte after the two lines.
  """
  def parse_header(content) when is_binary(content) do
    case Regex.run(@header, content) do
      [full, version, book, book_hash, body_hash] ->
        size = byte_size(full)

        {:ok,
         %{
           version: version,
           book: book,
           book_hash: book_hash,
           body_hash: body_hash,
           body: binary_part(content, size, byte_size(content) - size)
         }}

      _other ->
        :error
    end
  end

  @doc "Lowercase hex sha256 of a target body."
  def body_hash(body) when is_binary(body), do: sha256(body)

  @doc """
  Lowercase hex sha256 of the book at `book_rel` and the files it
  imports. See the module docs for the byte layout.
  """
  def book_hash(root, book_rel) when is_binary(root) and is_binary(book_rel) do
    root = Path.expand(root)
    absolute = Path.expand(book_rel, root)

    absolute
    |> book_files()
    |> Enum.map(fn file -> {relative_slash(root, file), File.read!(file)} end)
    |> Enum.sort()
    |> Enum.map(fn {rel, bytes} -> [rel, 0, bytes, 0] end)
    |> sha256()
  end

  @doc """
  Absolute paths of the book and every file it imports. Each path
  appears once. Discovery order, not the hash order.
  """
  def book_files(path) when is_binary(path) do
    {files, _seen} = walk(Path.expand(path), MapSet.new(), [])
    Enum.reverse(files)
  end

  @doc """
  Check every book, then write every target.

  `{:ok, lines}` is one `written` or `unchanged` line per target.
  An ExUnit target then adds one `skipped` line per skipped equation.
  An unchanged target is not opened for writing. `{:error, message}`
  means at least one book failed; nothing was written.
  """
  def generate(%Muro.Manifest{} = manifest, root, version)
      when is_binary(root) and is_binary(version) do
    root = Path.expand(root)

    with :ok <- reject_failing_books(manifest, root) do
      case render_all(manifest, root, version) do
        {:ok, files} -> {:ok, Enum.flat_map(files, &write_target(root, &1))}
        {:error, message} -> {:error, message <> "\nmuro.gen wrote nothing"}
      end
    end
  end

  @doc """
  Compare every target to its book. Writes nothing.

  `:ok` when every book checks and every target is the bytes `generate/3`
  would leave in place. `{:error, message}` lists every problem.
  """
  def check(%Muro.Manifest{} = manifest, root, version)
      when is_binary(root) and is_binary(version) do
    root = Path.expand(root)

    problems =
      Enum.flat_map(manifest.modules, fn entry ->
        problems_for(entry, root, version, manifest.fuel)
      end)

    if problems == [] do
      :ok
    else
      {:error, Enum.join(problems, "\n")}
    end
  end

  defp reject_failing_books(manifest, root) do
    failures =
      Enum.flat_map(manifest.modules, fn entry ->
        case check_book(entry, root, manifest.fuel) do
          :ok -> []
          {:error, message} -> [does_not_check(entry, message)]
        end
      end)

    if failures == [] do
      :ok
    else
      {:error, Enum.join(failures, "\n") <> "\nmuro.gen wrote nothing"}
    end
  end

  defp render_all(manifest, root, version) do
    Enum.reduce_while(manifest.modules, {:ok, []}, fn entry, {:ok, acc} ->
      case render(root, entry, version, manifest.fuel) do
        {:ok, contents, skips} -> {:cont, {:ok, acc ++ [{entry, contents, skips}]}}
        {:error, message} -> {:halt, {:error, does_not_check(entry, message)}}
      end
    end)
  end

  defp render(root, entry, version, fuel) do
    case emit_entry(root, entry, fuel) do
      {:ok, source, skips} ->
        file = settle(root, entry, version, format_elixir(source, entry.target, root), 3)

        if coherent?(file, root, entry, version) do
          {:ok, file, skips}
        else
          {:error, "generated header does not describe #{entry.target}"}
        end

      {:error, message} ->
        {:error, message}
    end
  end

  defp emit_entry(root, entry, fuel) do
    path = Muro.Manifest.book_path(root, entry)

    case Map.get(entry, :kind, :elixir) do
      :exunit ->
        opts = [fuel: fuel, root: root, book: entry.book]

        opts =
          case Map.get(entry, :impl) do
            nil -> opts
            impl -> Keyword.put(opts, :impl, impl)
          end

        case Muro.emit_exunit(path, entry.module, opts) do
          {:ok, %{source: source, skips: skips}} -> {:ok, source, skips}
          {:error, message} -> {:error, message}
        end

      _kind ->
        case Muro.emit_file(path, entry.module, fuel: fuel) do
          {:ok, source} -> {:ok, source, []}
          {:error, message} -> {:error, message}
        end
    end
  end

  defp coherent?(file, root, entry, version) do
    case parse_header(file) do
      {:ok, header} ->
        header.version == version and header.book == entry.book and
          header.book_hash == book_hash(root, entry.book) and
          header.body_hash == body_hash(header.body)

      :error ->
        false
    end
  end

  defp settle(root, entry, version, body, 0) do
    assemble(root, entry, version, body)
  end

  defp settle(root, entry, version, body, left) do
    file = assemble(root, entry, version, body)
    formatted = format_elixir(file, entry.target, root)

    case parse_header(formatted) do
      {:ok, %{body: ^body}} -> file
      {:ok, %{body: next}} -> settle(root, entry, version, next, left - 1)
      :error -> file
    end
  end

  defp assemble(root, entry, version, body) do
    header(version, entry.book, book_hash(root, entry.book), body_hash(body)) <> body
  end

  defp write_target(root, {entry, contents, skips}) do
    path = Muro.Manifest.target_path(root, entry)

    line =
      if File.regular?(path) and File.read!(path) == contents do
        "unchanged #{entry.target}"
      else
        File.mkdir_p!(Path.dirname(path))
        File.write!(path, contents)
        "written #{entry.target}"
      end

    [line | Enum.map(skips, &skip_line(entry, &1))]
  end

  defp skip_line(entry, skip) do
    "skipped #{entry.target}: #{skip.name} (#{skip.file}:#{skip.line}): #{skip.reason}"
  end

  defp problems_for(entry, root, version, fuel) do
    case check_book(entry, root, fuel) do
      :ok ->
        target_problems(entry, root, version, fuel, true)

      {:error, message} ->
        [does_not_check(entry, message) | target_problems(entry, root, version, fuel, false)]
    end
  end

  defp check_book(entry, root, fuel) do
    Muro.check_file(Muro.Manifest.book_path(root, entry), fuel: fuel)
  end

  defp target_problems(entry, root, version, fuel, book_ok?) do
    path = Muro.Manifest.target_path(root, entry)

    if File.regular?(path) do
      classify(File.read!(path), entry, root, version, fuel, book_ok?)
    else
      ["#{entry.target}: missing target for #{entry.book}"]
    end
  end

  defp classify(content, entry, root, version, fuel, book_ok?) do
    case parse_header(content) do
      :error ->
        differs_message(content, entry, root, version, fuel, book_ok?)

      {:ok, header} ->
        version_problem =
          if header.version == version do
            []
          else
            [
              "#{entry.target}: header says Muro #{header.version}, running #{version}, from #{entry.book}"
            ]
          end

        current = book_hash(root, entry.book)

        version_problem ++
          hash_problems(content, header, current, entry, root, version, fuel, book_ok?)
    end
  end

  defp hash_problems(content, header, current, entry, root, version, fuel, book_ok?) do
    cond do
      header.book != entry.book ->
        ["#{entry.target}: differs from what #{entry.book} emits"]

      header.book_hash != current ->
        [
          "#{entry.target}: stale target; #{entry.book} changed (book sha256 #{header.book_hash}, current #{current})"
        ]

      body_hash(header.body) != header.body_hash ->
        [
          "#{entry.target}: hand-edited target; #{entry.book} is unchanged and the body no longer matches its recorded sha256"
        ]

      header.version == version and book_ok? ->
        differs_message(content, entry, root, version, fuel, true)

      true ->
        []
    end
  end

  defp differs_message(content, entry, root, version, fuel, true) do
    case render(root, entry, version, fuel) do
      {:ok, ^content, _skips} -> []
      _other -> ["#{entry.target}: differs from what #{entry.book} emits"]
    end
  end

  defp differs_message(_content, _entry, _root, _version, _fuel, false), do: []

  defp does_not_check(entry, message) do
    "#{entry.target}: #{entry.book} does not check\n#{message}"
  end

  defp format_elixir(source, target, root) do
    formatted =
      if File.regular?(Path.join(root, ".formatter.exs")) do
        {formatter, _opts} =
          Mix.Tasks.Format.formatter_for_file(Path.join(root, target), root: root)

        formatter.(source)
      else
        source |> Code.format_string!() |> IO.iodata_to_binary()
      end

    ensure_newline(IO.iodata_to_binary(formatted))
  end

  defp ensure_newline(binary) do
    String.trim_trailing(binary, "\n") <> "\n"
  end

  defp walk(path, seen, acc) do
    cond do
      MapSet.member?(seen, path) ->
        {acc, seen}

      not File.regular?(path) ->
        {acc, seen}

      true ->
        seen = MapSet.put(seen, path)
        acc = [path | acc]
        follow_imports(path, seen, acc)
    end
  end

  defp follow_imports(path, seen, acc) do
    case File.read(path) do
      {:ok, source} ->
        case Muro.Parser.parse(source) do
          {:ok, book} ->
            Enum.reduce(import_paths(book, path), {acc, seen}, fn next, {acc, seen} ->
              walk(next, seen, acc)
            end)

          {:error, _message} ->
            {acc, seen}
        end

      {:error, _reason} ->
        {acc, seen}
    end
  end

  defp import_paths(book, path) do
    dir = Path.dirname(path)

    Enum.flat_map(book, fn entry ->
      case entry do
        %{kind: :import, path: rel} when is_binary(rel) -> [Path.expand(rel, dir)]
        _other -> []
      end
    end)
  end

  @doc """
  `path` relative to `root`, with `/` separators. A path outside
  `root` starts with `..`. The result is never absolute.
  """
  def relative_path(root, path) when is_binary(root) and is_binary(path) do
    relative_slash(root, path)
  end

  defp relative_slash(root, path) do
    root_parts = Path.split(Path.expand(root))
    path_parts = Path.split(Path.expand(path))
    {root_rest, path_rest} = drop_common(root_parts, path_parts)

    case List.duplicate("..", length(root_rest)) ++ path_rest do
      [] -> "."
      parts -> Enum.join(parts, "/")
    end
  end

  defp drop_common([same | root], [same | path]), do: drop_common(root, path)
  defp drop_common(root, path), do: {root, path}

  defp sha256(iodata) do
    :crypto.hash(:sha256, IO.iodata_to_binary(iodata)) |> Base.encode16(case: :lower)
  end
end
