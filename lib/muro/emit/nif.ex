defmodule Muro.Emit.Nif do
  @moduledoc """
  Build a NIF for the exported runs whose live arguments and result are `Nat`.

  The generated C is compiled with `muro__ALLOC` set to one block. The call
  copies the result out as an integer and resets the block, so the next call
  reuses it. `elixir_make` runs the makefile. A run that is not that shape
  stays in the C file and is not an entry. `run internal` is not an entry.

  C identifiers in this file come from `Muro.Emit.Name`, the same split the
  C emitter uses. The Elixir loader `muro_nif_load` is an Elixir function,
  not one of those identifiers.
  """

  alias Muro.Emit.Name

  # Same words `Muro.Emit` refuses as Elixir function names.
  @elixir_reserved ~w(
    true false nil
    when and or not in
    fn do end catch rescue after else
  ) |> MapSet.new()

  @nat Name.gen("nat") <> " *"

  @doc """
  Write the NIF sources next to the generated C and build `priv/<stem>.so`.

  Returns the new paths. An empty list means the book has no Nat entry.
  A Nat entry needs `elixir_make`. Without it, this raises `Mix.Error`
  and writes nothing.
  """
  def build(dir, stem, sigs) when is_binary(dir) and is_binary(stem) and is_list(sigs) do
    build(dir, stem, sigs, elixir_make_available?())
  end

  @doc false
  def build(dir, stem, sigs, available?)
      when is_binary(dir) and is_binary(stem) and is_list(sigs) and is_boolean(available?) do
    case Enum.filter(sigs, &nat_export?/1) do
      [] ->
        []

      exports ->
        require_elixir_make!(available?)
        entries = elixir_names(exports)
        File.write!(Path.join(dir, stem <> "_nif.h"), header(stem))
        File.write!(Path.join(dir, stem <> "_nif.c"), source(stem, entries))
        File.write!(Path.join(dir, stem <> ".mk"), makefile(stem))
        File.write!(Path.join(dir, stem <> ".ex"), elixir(stem, entries))

        ElixirMake.Compiler.make(
          Keyword.merge(Mix.Project.config(),
            make_cwd: dir,
            make_makefile: stem <> ".mk",
            make_targets: ["all"]
          ),
          []
        )

        [
          Path.join(dir, stem <> "_nif.h"),
          Path.join(dir, stem <> "_nif.c"),
          Path.join(dir, stem <> ".mk"),
          Path.join(dir, stem <> ".ex"),
          Path.join(dir, Path.join("priv", stem <> ".so"))
        ]
    end
  end

  @doc false
  def elixir_make_available? do
    Code.ensure_loaded?(ElixirMake.Compiler) and
      function_exported?(ElixirMake.Compiler, :make, 2)
  end

  @doc false
  def ensure_make!(sigs, available? \\ elixir_make_available?()) when is_list(sigs) do
    if Enum.any?(sigs, &nat_export?/1) do
      require_elixir_make!(available?)
    else
      :ok
    end
  end

  @doc false
  def require_elixir_make!(available? \\ elixir_make_available?()) do
    if available? do
      :ok
    else
      Mix.raise("""
      --backend c builds a NIF with elixir_make, which is not available.

      Add this to the project deps:

          {:elixir_make, "~> 0.10", runtime: false}

      Or run inside a project that depends on muro.
      """)
    end
  end

  defp nat_export?(%{export: true, ret: @nat, params: params}) do
    Enum.all?(params, fn {ty, _name} -> ty == @nat end)
  end

  defp nat_export?(_), do: false

  defp elixir_names(exports) do
    # The loader occupies this name. A Nat run that would spell the same takes a suffix.
    {rev, _} =
      Enum.reduce(exports, {[], MapSet.new(["muro_nif_load"])}, fn sig, {acc, used} ->
        {name, used} = claim(elixir_base(sig.name), used)
        {[{sig, name} | acc], used}
      end)

    Enum.reverse(rev)
  end

  defp elixir_base(c_name) do
    if String.match?(c_name, ~r/^[a-z_][A-Za-z0-9_]*$/) and c_name not in @elixir_reserved do
      c_name
    else
      "muro_" <> c_name
    end
  end

  # Elixir function names. The numeric tail is `Name.claim/2`. The spelling
  # itself is not in the C identifier split.
  defp claim(base, used), do: Name.claim(base, used)

  defp module_name(stem) do
    stem
    |> String.replace("-", "_")
    |> Macro.camelize()
    |> List.wrap()
    |> Module.concat()
  end

  defp header(stem) do
    guard = Name.gen("H_" <> Name.encode(stem) <> "_NIF")
    alloc = Name.gen("nif_alloc")

    """
    /* generated by muro — do not edit */
    #ifndef #{guard}
    #define #{guard}
    #include <stddef.h>
    void *#{alloc}(size_t);
    #endif
    """
  end

  defp makefile(stem) do
    """
    # generated by muro — do not edit
    CC ?= cc
    CFLAGS ?= -O2 -fPIC
    ERTS_INCLUDE_DIR ?= $(shell erl -noshell -eval 'io:format("~s/erts-~s/include",[code:root_dir(),erlang:system_info(version)]),halt().')

    UNAME_S := $(shell uname -s)
    ifeq ($(UNAME_S),Darwin)
    SO_FLAGS := -shared -undefined dynamic_lookup
    else
    SO_FLAGS := -shared
    endif

    .PHONY: all
    all: priv/#{stem}.so

    priv/#{stem}.so: #{stem}.o #{stem}_nif.o
    \tmkdir -p priv
    \t$(CC) $(SO_FLAGS) -o $@ #{stem}.o #{stem}_nif.o

    #{stem}.o: #{stem}.c #{stem}.h #{stem}_nif.h
    \t$(CC) $(CFLAGS) -I$(ERTS_INCLUDE_DIR) -D#{Name.gen("ALLOC")}=#{Name.gen("nif_alloc")} -include #{stem}_nif.h -c #{stem}.c -o $@

    #{stem}_nif.o: #{stem}_nif.c #{stem}.h #{stem}_nif.h
    \t$(CC) $(CFLAGS) -I$(ERTS_INCLUDE_DIR) -c #{stem}_nif.c -o $@
    """
  end

  defp elixir(stem, entries) do
    funs =
      Enum.map_join(entries, "\n", fn {sig, name} ->
        args = sig.params |> Enum.with_index() |> Enum.map_join(", ", fn {_, i} -> "_a#{i}" end)

        if args == "" do
          "  def #{name}, do: :erlang.nif_error(:nif_not_loaded)"
        else
          "  def #{name}(#{args}), do: :erlang.nif_error(:nif_not_loaded)"
        end
      end)

    """
    defmodule #{inspect(module_name(stem))} do
      # Generated by Muro. Evidence never becomes a run.
      @on_load :muro_nif_load

      def muro_nif_load do
        path = Path.join(__DIR__, "priv/#{stem}")
        :erlang.load_nif(String.to_charlist(path), 0)
      end

    #{funs}
    end
    """
  end

  defp source(stem, entries) do
    {funs, table} =
      entries
      |> Enum.with_index()
      |> Enum.map(fn {{sig, elixir_name}, i} ->
        c_fun = Name.gen("nif_e", i)
        {entry(c_fun, sig), {elixir_name, length(sig.params), c_fun}}
      end)
      |> Enum.unzip()

    rows =
      Enum.map_join(table, ",\n  ", fn {name, arity, c_fun} ->
        ~s|{"#{name}", #{arity}, #{c_fun}, ERL_NIF_DIRTY_JOB_CPU_BOUND}|
      end)

    """
    /* generated by muro — do not edit */
    #include <erl_nif.h>
    #include <stdint.h>
    #include <stdlib.h>
    #include "#{stem}.h"

    #{nif_runtime()}

    #{Enum.join(funs, "\n\n")}

    static ErlNifFunc #{Name.gen("nif_funcs")}[] = {
      #{rows}
    };

    #{nif_load_unload()}

    ERL_NIF_INIT(Elixir.#{inspect(module_name(stem))}, #{Name.gen("nif_funcs")}, #{Name.gen("nif_load")}, NULL, NULL, #{Name.gen("nif_unload")})
    """
  end

  defp entry(c_fun, sig) do
    env = Name.gen("nif_env")
    argc = Name.gen("nif_argc")
    argv = Name.gen("nif_argv")
    out = Name.gen("out")
    result = Name.gen("r")
    ok = Name.gen("ok")
    nat = Name.gen("nat")
    of = Name.gen("nif_of")
    read = Name.gen("nif_read")
    reset = Name.gen("nif_reset")
    lock = Name.gen("nif_lock")

    binds =
      sig.params
      |> Enum.with_index()
      |> Enum.map_join("\n  ", fn {_, i} ->
        "if (!enif_get_uint64(#{env}, #{argv}[#{i}], &#{Name.gen("a", i)})) return enif_make_badarg(#{env});"
      end)

    decls =
      case length(sig.params) do
        0 ->
          "  ErlNifUInt64 #{out};"

        n ->
          names = Enum.map_join(0..(n - 1), ", ", &Name.gen("a", &1))
          "  ErlNifUInt64 #{names}, #{out};"
      end

    args =
      sig.params
      |> Enum.with_index()
      |> Enum.map_join(", ", fn {_, i} -> "#{of}(#{Name.gen("a", i)})" end)

    body_binds = if binds == "", do: "", else: "  #{binds}\n"

    """
    static ERL_NIF_TERM #{c_fun}(ErlNifEnv *#{env}, int #{argc}, const ERL_NIF_TERM #{argv}[]) {
      (void)#{argc};
    #{decls}
    #{body_binds}  enif_mutex_lock(#{lock});
      #{nat} *#{result} = #{sig.name}(#{args});
      int #{ok} = #{read}(#{result}, &#{out});
      #{reset}();
      enif_mutex_unlock(#{lock});
      if (!#{ok}) return enif_make_badarg(#{env});
      return enif_make_uint64(#{env}, #{out});
    }
    """
    |> String.trim()
  end

  defp nif_load_unload do
    env = Name.gen("nif_env")
    priv = Name.gen("nif_priv")
    info = Name.gen("nif_info")
    lock = Name.gen("nif_lock")
    chunks = Name.gen("nif_chunks")
    reset = Name.gen("nif_reset")
    load = Name.gen("nif_load")
    unload = Name.gen("nif_unload")

    """
    static int #{load}(ErlNifEnv *#{env}, void **#{priv}, ERL_NIF_TERM #{info}) {
      (void)#{env};
      (void)#{priv};
      (void)#{info};
      #{lock} = enif_mutex_create("muro_nif");
      #{chunks} = 0;
      return #{lock} ? 0 : 1;
    }

    static void #{unload}(ErlNifEnv *#{env}, void *#{priv}) {
      (void)#{env};
      (void)#{priv};
      #{reset}();
      if (#{chunks}) {
        enif_free(#{chunks});
        #{chunks} = 0;
      }
      if (#{lock}) enif_mutex_destroy(#{lock});
    }
    """
    |> String.trim()
  end

  defp nif_runtime do
    chunk = Name.gen("nif_chunk")
    lock = Name.gen("nif_lock")
    chunks = Name.gen("nif_chunks")
    alloc = Name.gen("nif_alloc")
    reset = Name.gen("nif_reset")
    of = Name.gen("nif_of")
    read = Name.gen("nif_read")
    nat = Name.gen("nat")
    tag = Name.gen("field_tag")
    suc = Name.gen("field_suc")
    c = Name.gen("c")
    n = Name.gen("n")
    s = Name.gen("s")
    k = Name.gen("k")
    p = Name.gen("p")
    out = Name.gen("out")
    align = Name.gen("nif_align")
    cap = Name.gen("nif_cap")
    nxt = Name.gen("nif_next")

    """
    struct #{chunk} {
      struct #{chunk} *prev;
      size_t at;
      size_t cap;
      unsigned char data[];
    };

    static ErlNifMutex *#{lock};
    static struct #{chunk} *#{chunks};

    /* One block for the call. The generated C allocates through this name.
       Calls take the lock, so two schedulers do not share the cursor. */
    void *#{alloc}(size_t #{n}) {
      size_t #{align} = (#{n} + (sizeof(void *) - 1)) & ~(sizeof(void *) - 1);
      if (#{align} == 0) #{align} = sizeof(void *);
      struct #{chunk} *#{c} = #{chunks};
      if (#{c} == 0 || #{c}->at + #{align} > #{c}->cap) {
        size_t #{cap} = #{c} ? #{c}->cap * 2 : 4096;
        if (#{cap} < #{align}) #{cap} = #{align};
        struct #{chunk} *#{nxt} = enif_alloc(sizeof(struct #{chunk}) + #{cap});
        if (#{nxt} == 0) abort();
        #{nxt}->prev = #{c};
        #{nxt}->at = 0;
        #{nxt}->cap = #{cap};
        #{chunks} = #{nxt};
        #{c} = #{nxt};
      }
      void *#{p} = #{c}->data + #{c}->at;
      #{c}->at += #{align};
      return #{p};
    }

    static void #{reset}(void) {
      struct #{chunk} *#{c} = #{chunks};
      while (#{c} && #{c}->prev) {
        struct #{chunk} *#{p} = #{c}->prev;
        enif_free(#{c});
        #{c} = #{p};
      }
      if (#{c}) #{c}->at = 0;
      #{chunks} = #{c};
    }

    static #{nat} *#{of}(ErlNifUInt64 #{k}) {
      #{nat} *#{n} = #{alloc}(sizeof *#{n});
      if (#{n} == 0) abort();
      #{n}->#{tag} = 0;
      #{n}->#{suc} = 0;
      while (#{k} > 0) {
        #{nat} *#{s} = #{alloc}(sizeof *#{s});
        if (#{s} == 0) abort();
        #{s}->#{tag} = 1;
        #{s}->#{suc} = #{n};
        #{n} = #{s};
        #{k}--;
      }
      return #{n};
    }

    static int #{read}(const #{nat} *#{n}, ErlNifUInt64 *#{out}) {
      ErlNifUInt64 #{k} = 0;
      while (#{n} != 0 && #{n}->#{tag} == 1) {
        if (#{k} == UINT64_MAX) return 0;
        #{k}++;
        #{n} = #{n}->#{suc};
      }
      if (#{n} == 0 || #{n}->#{tag} != 0) return 0;
      *#{out} = #{k};
      return 1;
    }
    """
    |> String.trim()
  end
end
