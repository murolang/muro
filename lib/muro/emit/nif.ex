defmodule Muro.Emit.Nif do
  @moduledoc """
  Build a NIF for the exported runs whose live arguments and result are `Nat`.

  The generated C is compiled with `MURO_ALLOC` set to one block. The call
  copies the result out as an integer and resets the block, so the next call
  reuses it. `elixir_make` runs the makefile. A run that is not that shape
  stays in the C file and is not an entry. `run internal` is not an entry.
  """

  # Same words `Muro.Emit` refuses as Elixir function names.
  @elixir_reserved ~w(
    true false nil
    when and or not in
    fn do end catch rescue after else
  ) |> MapSet.new()

  @nat "muro_nat *"

  @doc """
  Write the NIF sources next to the generated C and build `priv/<stem>.so`.

  Returns the new paths. An empty list means the book has no Nat entry.
  """
  def build(dir, stem, sigs) when is_binary(dir) and is_binary(stem) and is_list(sigs) do
    case Enum.filter(sigs, &nat_export?/1) do
      [] ->
        []

      exports ->
        entries = elixir_names(exports)
        File.write!(Path.join(dir, stem <> "_nif.h"), header(stem))
        File.write!(Path.join(dir, stem <> "_nif.c"), source(stem, entries))
        File.write!(Path.join(dir, stem <> ".mk"), makefile(stem))
        File.write!(Path.join(dir, stem <> ".ex"), elixir(stem, entries))

        ElixirMake.Compiler.make(
          Keyword.merge(Mix.Project.config(),
            make_cwd: dir,
            make_makefile: stem <> ".mk",
            make_targets: ["all"]
          ),
          []
        )

        [
          Path.join(dir, stem <> "_nif.h"),
          Path.join(dir, stem <> "_nif.c"),
          Path.join(dir, stem <> ".mk"),
          Path.join(dir, stem <> ".ex"),
          Path.join(dir, Path.join("priv", stem <> ".so"))
        ]
    end
  end

  defp nat_export?(%{export: true, ret: @nat, params: params}) do
    Enum.all?(params, fn {ty, _name} -> ty == @nat end)
  end

  defp nat_export?(_), do: false

  defp elixir_names(exports) do
    # The loader occupies this name. A Nat run that would spell the same takes a suffix.
    {rev, _} =
      Enum.reduce(exports, {[], MapSet.new(["muro_nif_load"])}, fn sig, {acc, used} ->
        {name, used} = claim(elixir_base(sig.name), used)
        {[{sig, name} | acc], used}
      end)

    Enum.reverse(rev)
  end

  defp elixir_base(c_name) do
    if String.match?(c_name, ~r/^[a-z_][A-Za-z0-9_]*$/) and c_name not in @elixir_reserved do
      c_name
    else
      "muro_" <> c_name
    end
  end

  defp claim(base, used) do
    name = if MapSet.member?(used, base), do: bump(base, 2, used), else: base
    {name, MapSet.put(used, name)}
  end

  defp bump(base, i, used) do
    n = "#{base}_#{i}"
    if MapSet.member?(used, n), do: bump(base, i + 1, used), else: n
  end

  defp module_name(stem) do
    stem
    |> String.replace("-", "_")
    |> Macro.camelize()
    |> List.wrap()
    |> Module.concat()
  end

  defp header(stem) do
    guard = "MURO_" <> String.upcase(stem) <> "_NIF_H"

    """
    /* generated by muro — do not edit */
    #ifndef #{guard}
    #define #{guard}
    #include <stddef.h>
    void *muro_nif_alloc(size_t n);
    #endif
    """
  end

  defp makefile(stem) do
    """
    # generated by muro — do not edit
    CC ?= cc
    CFLAGS ?= -O2 -fPIC
    ERTS_INCLUDE_DIR ?= $(shell erl -noshell -eval 'io:format("~s/erts-~s/include",[code:root_dir(),erlang:system_info(version)]),halt().')

    UNAME_S := $(shell uname -s)
    ifeq ($(UNAME_S),Darwin)
    SO_FLAGS := -shared -undefined dynamic_lookup
    else
    SO_FLAGS := -shared
    endif

    .PHONY: all
    all: priv/#{stem}.so

    priv/#{stem}.so: #{stem}.o #{stem}_nif.o
    \tmkdir -p priv
    \t$(CC) $(SO_FLAGS) -o $@ #{stem}.o #{stem}_nif.o

    #{stem}.o: #{stem}.c #{stem}.h #{stem}_nif.h
    \t$(CC) $(CFLAGS) -I$(ERTS_INCLUDE_DIR) -DMURO_ALLOC=muro_nif_alloc -include #{stem}_nif.h -c #{stem}.c -o $@

    #{stem}_nif.o: #{stem}_nif.c #{stem}.h #{stem}_nif.h
    \t$(CC) $(CFLAGS) -I$(ERTS_INCLUDE_DIR) -c #{stem}_nif.c -o $@
    """
  end

  defp elixir(stem, entries) do
    funs =
      Enum.map_join(entries, "\n", fn {sig, name} ->
        args = sig.params |> Enum.with_index() |> Enum.map_join(", ", fn {_, i} -> "_a#{i}" end)

        if args == "" do
          "  def #{name}, do: :erlang.nif_error(:nif_not_loaded)"
        else
          "  def #{name}(#{args}), do: :erlang.nif_error(:nif_not_loaded)"
        end
      end)

    """
    defmodule #{inspect(module_name(stem))} do
      # Generated by Muro. Evidence never becomes a run.
      @on_load :muro_nif_load

      def muro_nif_load do
        path = Path.join(__DIR__, "priv/#{stem}")
        :erlang.load_nif(String.to_charlist(path), 0)
      end

    #{funs}
    end
    """
  end

  defp source(stem, entries) do
    used = MapSet.new(Enum.map(entries, fn {sig, _} -> sig.name end))

    {funs, table, _} =
      Enum.reduce(Enum.with_index(entries), {[], [], used}, fn {{sig, elixir_name}, i},
                                                               {funs, table, used} ->
        {c_fun, used} = entry_fun(i, used)

        {[entry(c_fun, sig) | funs], [{elixir_name, length(sig.params), c_fun} | table], used}
      end)

    funs = Enum.reverse(funs)
    table = Enum.reverse(table)

    rows =
      Enum.map_join(table, ",\n  ", fn {name, arity, c_fun} ->
        ~s|{"#{name}", #{arity}, #{c_fun}, ERL_NIF_DIRTY_JOB_CPU_BOUND}|
      end)

    """
    /* generated by muro — do not edit */
    #include <erl_nif.h>
    #include <stdint.h>
    #include <stdlib.h>
    #include "#{stem}.h"

    struct muro_nif_chunk {
      struct muro_nif_chunk *prev;
      size_t at;
      size_t cap;
      unsigned char data[];
    };

    static ErlNifMutex *muro_nif_lock;
    static struct muro_nif_chunk *muro_nif_chunks;

    /* One block for the call. The generated C allocates through this name.
       Calls take the lock, so two schedulers do not share the cursor. */
    void *muro_nif_alloc(size_t n) {
      size_t align = (n + (sizeof(void *) - 1)) & ~(sizeof(void *) - 1);
      if (align == 0) align = sizeof(void *);
      struct muro_nif_chunk *c = muro_nif_chunks;
      if (c == 0 || c->at + align > c->cap) {
        size_t cap = c ? c->cap * 2 : 4096;
        if (cap < align) cap = align;
        struct muro_nif_chunk *next = enif_alloc(sizeof(struct muro_nif_chunk) + cap);
        if (next == 0) abort();
        next->prev = c;
        next->at = 0;
        next->cap = cap;
        muro_nif_chunks = next;
        c = next;
      }
      void *p = c->data + c->at;
      c->at += align;
      return p;
    }

    static void muro_nif_reset(void) {
      struct muro_nif_chunk *c = muro_nif_chunks;
      while (c && c->prev) {
        struct muro_nif_chunk *p = c->prev;
        enif_free(c);
        c = p;
      }
      if (c) c->at = 0;
      muro_nif_chunks = c;
    }

    static muro_nat *muro_nif_of(ErlNifUInt64 k) {
      muro_nat *n = muro_nif_alloc(sizeof *n);
      if (n == 0) abort();
      n->tag = 0;
      n->suc = 0;
      while (k > 0) {
        muro_nat *s = muro_nif_alloc(sizeof *s);
        if (s == 0) abort();
        s->tag = 1;
        s->suc = n;
        n = s;
        k--;
      }
      return n;
    }

    static int muro_nif_read(const muro_nat *n, ErlNifUInt64 *out) {
      ErlNifUInt64 k = 0;
      while (n != 0 && n->tag == 1) {
        if (k == UINT64_MAX) return 0;
        k++;
        n = n->suc;
      }
      if (n == 0 || n->tag != 0) return 0;
      *out = k;
      return 1;
    }

    #{Enum.join(funs, "\n\n")}

    static ErlNifFunc muro_nif_funcs[] = {
      #{rows}
    };

    static int muro_nif_load(ErlNifEnv *env, void **priv, ERL_NIF_TERM info) {
      (void)env;
      (void)priv;
      (void)info;
      muro_nif_lock = enif_mutex_create("muro_nif");
      muro_nif_chunks = 0;
      return muro_nif_lock ? 0 : 1;
    }

    static void muro_nif_unload(ErlNifEnv *env, void *priv) {
      (void)env;
      (void)priv;
      muro_nif_reset();
      if (muro_nif_chunks) {
        enif_free(muro_nif_chunks);
        muro_nif_chunks = 0;
      }
      if (muro_nif_lock) enif_mutex_destroy(muro_nif_lock);
    }

    ERL_NIF_INIT(Elixir.#{inspect(module_name(stem))}, muro_nif_funcs, muro_nif_load, NULL, NULL, muro_nif_unload)
    """
  end

  defp entry(c_fun, sig) do
    binds =
      sig.params
      |> Enum.with_index()
      |> Enum.map_join("\n  ", fn {_, i} ->
        "if (!enif_get_uint64(env, argv[#{i}], &a#{i})) return enif_make_badarg(env);"
      end)

    decls =
      case length(sig.params) do
        0 -> "  ErlNifUInt64 out;"
        n -> "  ErlNifUInt64 " <> Enum.map_join(0..(n - 1), ", ", &"a#{&1}") <> ", out;"
      end

    args =
      sig.params
      |> Enum.with_index()
      |> Enum.map_join(", ", fn {_, i} -> "muro_nif_of(a#{i})" end)

    body_binds = if binds == "", do: "", else: "  #{binds}\n"

    """
    static ERL_NIF_TERM #{c_fun}(ErlNifEnv *env, int argc, const ERL_NIF_TERM argv[]) {
      (void)argc;
    #{decls}
    #{body_binds}  enif_mutex_lock(muro_nif_lock);
      muro_nat *r = #{sig.name}(#{args});
      int ok = muro_nif_read(r, &out);
      muro_nif_reset();
      enif_mutex_unlock(muro_nif_lock);
      if (!ok) return enif_make_badarg(env);
      return enif_make_uint64(env, out);
    }
    """
    |> String.trim()
  end

  defp entry_fun(i, used) do
    base = "muro_nif_e#{i}"
    claim_c(base, used)
  end

  defp claim_c(base, used) do
    name = if MapSet.member?(used, base), do: bump(base, 2, used), else: base
    {name, MapSet.put(used, name)}
  end
end
