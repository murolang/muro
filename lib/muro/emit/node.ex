defmodule Muro.Emit.Node do
  @moduledoc """
  Emit one native BEAM call for each `cross`.

  `--node` names the BEAM node. The registered name on that node is
  the scheme. A `move cross` names that scheme. A `read cross` uses
  the scheme its endpoint names. The monitor is
  `:erlang.monitor(:process, {name, node})`, installed before
  `GenServer.call({name, node}, {:muro_read, scheme}, timeout)`.
  A `stay` emits no call. The bits stay on the session. `run` is
  not emitted here.

  The BEAM runs the call. The proof stops at the move.
  """

  @doc """
  Render `book` as one Elixir file. `stem` is the source stem (`place`).
  The module is that stem plus `Node` (`PlaceNode`). `node` is the
  BEAM node the calls use.
  """
  def render(book, stem, node) when is_list(book) and is_binary(stem) and is_atom(node) do
    funs = functions(book)
    {:ok, source(module_name(stem), node, funs)}
  end

  defp functions(book) do
    {funs, _} =
      book
      |> Enum.filter(&cross?/1)
      |> Enum.reduce({[], MapSet.new()}, fn entry, {acc, used} ->
        scheme = scheme_of(entry, book)
        {fname, used} = claim(fun_name(scheme, entry.place), used)
        {[{fname, scheme} | acc], used}
      end)

    Enum.reverse(funs)
  end

  defp cross?(%{kind: :move, mark: :cross}), do: true
  defp cross?(%{kind: :read, mark: :cross}), do: true
  defp cross?(_), do: false

  defp scheme_of(%{kind: :move, scheme: scheme}, _book), do: scheme

  defp scheme_of(%{kind: :read, endpoint: ename}, book) do
    %{scheme: scheme} =
      Enum.find(book, fn entry -> match?(%{kind: :endpoint, name: ^ename}, entry) end)

    scheme
  end

  defp source(parent, node, funs) do
    calls =
      funs
      |> Enum.map_join("\n\n", fn {fname, scheme} -> call_fun(fname, scheme) end)
      |> indent(2)

    body = if calls == "", do: "", else: "\n\n" <> calls

    """
    defmodule #{parent} do
      # Generated by Muro. The BEAM runs this call.
      # The proof stops at the move.
      # The scheme is registered on this node. The monitor is that incarnation.
      # A cross reading is this same call. The bits stay on the session.

      @node #{inspect(node)}

      def node, do: @node#{body}
    end
    """
  end

  defp call_fun(fname, scheme) do
    name = inspect(String.to_atom(scheme))
    msg = inspect({:muro_read, scheme})

    """
    def #{fname}(timeout \\\\ 5000) do
      dest = {#{name}, @node}
      ref = :erlang.monitor(:process, dest)

      receive do
        {:DOWN, ^ref, :process, _, reason} ->
          {:error, reason}
      after
        0 ->
          try do
            GenServer.call(dest, #{msg}, timeout)
          catch
            :exit, reason ->
              {:error, reason}
          after
            Process.demonitor(ref, [:flush])
          end
      end
    end
    """
    |> String.trim_trailing()
  end

  defp module_name(stem) do
    stem
    |> String.replace("-", "_")
    |> Macro.camelize()
    |> Kernel.<>("Node")
  end

  defp fun_name(scheme, place), do: "cross_#{slug(scheme)}_at_#{slug(place)}"

  defp slug(name) do
    name
    |> String.replace("-", "_")
    |> String.replace(~r/[^A-Za-z0-9_]/, "_")
  end

  defp claim(base, used) do
    name = if MapSet.member?(used, base), do: bump(base, 2, used), else: base
    {name, MapSet.put(used, name)}
  end

  defp bump(base, i, used) do
    name = "#{base}#{i}"

    if MapSet.member?(used, name), do: bump(base, i + 1, used), else: name
  end

  defp indent(code, n) do
    pad = String.duplicate(" ", n)

    code
    |> String.trim_trailing()
    |> String.split("\n")
    |> Enum.map_join("\n", fn
      "" -> ""
      line -> pad <> line
    end)
  end
end
