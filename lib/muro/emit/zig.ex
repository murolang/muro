  defp scan_funs(funs) do
    Enum.reduce(
      funs,
      %{ctors: MapSet.new(), atoms: MapSet.new(), steps: %{}, pair: false, stream: false},
      fn fun, acc ->
        scan_tm(fun.body, acc)
      end
    )
  end

  defp scan_tm({:pair, a, b}, acc), do: scan_tm(b, scan_tm(a, %{acc | pair: true}))

  defp scan_tm({:uncons, e}, acc), do: scan_tm(e, %{acc | pair: true, stream: true})

  defp scan_tm({:letp, _a, _b, e, body}, acc) do
    scan_tm(body, scan_tm(e, %{acc | pair: true}))
  end

  defp scan_tm({:stream, seed, caps, name}, acc) do
    acc = %{acc | stream: true, pair: true}
    acc = note_step(acc, name, length(caps))
    acc = scan_tm(seed, acc)
    Enum.reduce(caps, acc, fn {_n, tm}, acc -> scan_tm(tm, acc) end)
  end

  defp scan_tm({:con, "Atom", name, []}, acc) do
    %{acc | atoms: MapSet.put(acc.atoms, name)}
  end

  defp scan_tm({:con, d, c, args}, acc) do
    acc = %{acc | ctors: MapSet.put(acc.ctors, {d, c})}
    Enum.reduce(args, acc, &scan_tm/2)
  end

  defp scan_tm({:match, s, arms}, acc) do
    acc = scan_tm(s, acc)

    Enum.reduce(arms, acc, fn {:arm, _, _, body}, acc -> scan_tm(body, acc) end)
  end

  defp scan_tm(tm, acc) when is_tuple(tm) do
    tm |> Tuple.to_list() |> Enum.reduce(acc, &scan_tm/2)
  end

  defp scan_tm(tm, acc) when is_list(tm), do: Enum.reduce(tm, acc, &scan_tm/2)
  defp scan_tm(_tm, acc), do: acc

  defp note_step(acc, name, n) do
    case Map.fetch(acc.steps, name) do
      :error -> %{acc | steps: Map.put(acc.steps, name, n)}
      {:ok, ^n} -> acc
      {:ok, _} -> acc
    end
  end

  defp file_base(name, flags) do
    base = zig_base(name)

    if file_clash?(base, flags) do
      zig_base("muro_" <> base)
    else
      base
    end
  end

  defp file_clash?(base, flags) do
    MapSet.member?(@helper_names, base) or
      String.match?(base, ~r/^a[0-9]+$/) or
      (flags.pair and (base == "fst" or base == "snd")) or
      (flags.stream and base == "step")
  end

  defp zig_base(name) do
    n =
      name
      |> String.replace("-", "_")
      |> String.replace("'", "_")

    cond do
      n == "" or n == "_" ->
        "x"

      String.match?(n, ~r/^[0-9]/) ->
        "muro_" <> n

      MapSet.member?(@keywords, n) ->
        "muro_" <> n

      MapSet.member?(@primitives, n) ->
        "muro_" <> n

      MapSet.member?(@reserved, n) ->
        "muro_" <> n

      String.starts_with?(n, "_") ->
        "muro_" <> n

      String.match?(n, ~r/^[iu][0-9]+$/) ->
        "muro_" <> n

      String.match?(n, ~r/^muro_s[0-9]+$/) ->
        "muro_" <> n

      String.match?(n, ~r/^muro_[pct][0-9]+$/) ->
        "muro_" <> n

      String.match?(n, ~r/^muro_blk[0-9]+$/) ->
        "muro_" <> n

      String.match?(n, ~r/^muro_env_[0-9]+$/) ->
        "muro_" <> n

      String.match?(n, ~r/^muro_step_[0-9]+$/) ->
        "muro_" <> n

      String.starts_with?(n, "muro_val_") ->
        "muro_" <> n

      String.starts_with?(n, "muro_atom_") ->
        "muro_" <> n

      true ->
        n
    end
  end

  defp claim(base, used) do
    name = if MapSet.member?(used, base), do: bump(base, 2, used), else: base
    {name, MapSet.put(used, name)}
  end

  defp bump(base, i, used) do
    n = "#{base}_#{i}"
    if MapSet.member?(used, n), do: bump(base, i + 1, used), else: n
  end
end
